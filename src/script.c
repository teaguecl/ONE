// --- memory callbacks --------------------------------------------------------------------------------------------
// emu.addMemoryCallback(callback, callbackType, startAddress, endAddress, cpuType, memType): callback(address, value)
// for CPU reads, writes or instruction starts in the range (CPU address space only so far). A read or write callback
// that returns a number changes the value read or written.

#define MAX_MEM_CALLBACKS 256

typedef struct {
    script_t *script;
    int ref; // the function, in the script's registry
    int type;
    uint16_t start, end;
} mem_callback;

bool script_hook_read = false, script_hook_write = false, script_hook_exec = false;
uint8_t script_watch[0x10000];
static mem_callback mem_callbacks[MAX_MEM_CALLBACKS];
static int mem_callback_n = 0;

static void rebuild_watch(void)
{
    memset(script_watch, 0, sizeof(script_watch));
    script_hook_read = script_hook_write = script_hook_exec = false;
    for (int i = 0; i < mem_callback_n; i++) {
        const mem_callback *m = &mem_callbacks[i];
        for (uint32_t a = m->start; a <= m->end; a++) {
            script_watch[a] |= (uint8_t)(1u << m->type);
        }
        script_hook_read = script_hook_read || m->type == 0;
        script_hook_write = script_hook_write || m->type == 1;
        script_hook_exec = script_hook_exec || m->type == 2;
    }
}

static void remove_mem_callbacks_of(script_t *s)
{
    int kept = 0;
    for (int i = 0; i < mem_callback_n; i++) {
        if (mem_callbacks[i].script != s) {
            mem_callbacks[kept++] = mem_callbacks[i];
        }
    }
    mem_callback_n = kept;
    rebuild_watch();
}

static void mem_callback_args(lua_State *L, int *type, uint16_t *start, uint16_t *end)
{
    lua_Integer t = luaL_checkinteger(L, 2);
    luaL_argcheck(L, t >= 0 && t <= 2, 2, "not an emu.callbackType value");
    lua_Integer first = luaL_checkinteger(L, 3);
    lua_Integer last = luaL_optinteger(L, 4, first);
    luaL_argcheck(L, first >= 0 && first <= 0xFFFF && last >= first && last <= 0xFFFF, 3, "addresses $0000-$FFFF");
    lua_Integer mem = luaL_optinteger(L, 6, MEM_NES);
    luaL_argcheck(L, mem == MEM_NES, 6, "only emu.memType.nesMemory (the CPU's address space) so far");
    *type = (int)t;
    *start = (uint16_t)first;
    *end = (uint16_t)last;
}

static int l_add_memory_callback(lua_State *L)
{
    luaL_checktype(L, 1, LUA_TFUNCTION);
    int type;
    uint16_t start, end;
    mem_callback_args(L, &type, &start, &end);
    if (mem_callback_n == MAX_MEM_CALLBACKS) {
        return luaL_error(L, "too many memory callbacks (%d)", MAX_MEM_CALLBACKS);
    }
    lua_pushvalue(L, 1);
    mem_callback *m = &mem_callbacks[mem_callback_n++];
    m->script = script_of(L);
    m->ref = luaL_ref(L, LUA_REGISTRYINDEX);
    m->type = type;
    m->start = start;
    m->end = end;
    rebuild_watch();
    lua_pushinteger(L, m->ref);
    return 1;
}

// emu.removeMemoryCallback(reference, callbackType, startAddress, endAddress, cpuType, memType)
static int l_remove_memory_callback(lua_State *L)
{
    lua_Integer ref = luaL_checkinteger(L, 1);
    int type;
    uint16_t start, end;
    mem_callback_args(L, &type, &start, &end);
    script_t *s = script_of(L);
    int kept = 0;
    for (int i = 0; i < mem_callback_n; i++) {
        const mem_callback *m = &mem_callbacks[i];
        if (m->script == s && m->ref == ref && m->type == type && m->start == start && m->end == end) {
            luaL_unref(L, LUA_REGISTRYINDEX, m->ref);
        } else {
            mem_callbacks[kept++] = *m;
        }
    }
    mem_callback_n = kept;
    rebuild_watch();
    return 0;
}

static bool call_with(script_t *s, int nargs, int nresults); // (below)
static void close_failed(void);

// Run the callbacks of this type that cover the address; returns the (possibly changed) value
static uint8_t run_mem_callbacks(int type, uint16_t address, uint8_t value)
{
    dispatch_depth++;
    for (int i = 0; i < mem_callback_n; i++) {
        mem_callback *m = &mem_callbacks[i];
        if (m->type != type || address < m->start || address > m->end || m->script->failed) {
            continue;
        }
        lua_State *L = m->script->L;
        lua_rawgeti(L, LUA_REGISTRYINDEX, m->ref);
        lua_pushinteger(L, address);
        lua_pushinteger(L, value);
        if (call_with(m->script, 2, 1)) {
            if (type != 2 && lua_isinteger(L, -1)) {
                value = (uint8_t)lua_tointeger(L, -1);
            }
            lua_pop(L, 1);
        }
    }
    if (--dispatch_depth == 0) {
        close_failed();
    }
    return value;
}

uint8_t script_mem_read(uint16_t address, uint8_t value)
{
    return run_mem_callbacks(0, address, value);
}

uint8_t script_mem_write(uint16_t address, uint8_t value)
{
    return run_mem_callbacks(1, address, value);
}

void script_mem_exec(uint16_t pc)
{
    run_mem_callbacks(2, pc, cpu_debug_read(pc));
}

// --- save states -------------------------------------------------------------------------------------------------
// A state object (userdata) is filled at the next point where ONE can take a state: a few PPU dots after the end of
// the picture (an endFrame callback's state is taken right after it). Loading happens at the next instruction.

#define STATE_META         "one.savestate"
#define MAX_PENDING_STATES 32

typedef struct {
    uint8_t *data;
    size_t size;
    bool pending;
} state_obj;

static struct {
    script_t *script;
    int ref; // keeps the object alive until it is filled
} pending_states[MAX_PENDING_STATES];
static int pending_state_n = 0;

static void state_captured(uint8_t *data, size_t size, void *context)
{
    (void)context;
    for (int i = 0; i < pending_state_n; i++) {
        lua_State *L = pending_states[i].script->L;
        lua_rawgeti(L, LUA_REGISTRYINDEX, pending_states[i].ref);
        state_obj *st = luaL_testudata(L, -1, STATE_META);
        if (st != NULL) {
            free(st->data);
            st->data = NULL;
            st->size = 0;
            st->data = (data != NULL) ? malloc(size) : NULL;
            if (st->data != NULL) {
                memcpy(st->data, data, size);
                st->size = size;
            }
            st->pending = false;
        }
        lua_pop(L, 1);
        luaL_unref(L, LUA_REGISTRYINDEX, pending_states[i].ref);
    }
    pending_state_n = 0;
    free(data);
}

static void forget_pending_states_of(script_t *s)
{
    int kept = 0;
    for (int i = 0; i < pending_state_n; i++) {
        if (pending_states[i].script != s) {
            pending_states[kept++] = pending_states[i];
        }
    }
    pending_state_n = kept;
    if (pending_state_n == 0) {
        savestate_capture(NULL, NULL);
    }
}

static int state_gc(lua_State *L)
{
    state_obj *st = luaL_checkudata(L, 1, STATE_META);
    free(st->data);
    st->data = NULL;
    return 0;
}

// one.newState(): an empty state object (the FCEUX layer's savestate.object())
static int l_new_state(lua_State *L)
{
    state_obj *st = lua_newuserdatauv(L, sizeof(state_obj), 0);
    memset(st, 0, sizeof(*st));
    luaL_setmetatable(L, STATE_META);
    return 1;
}

// one.saveState(state): take the machine's state into it (at the next possible point, see above)
static int l_save_state(lua_State *L)
{
    state_obj *st = luaL_checkudata(L, 1, STATE_META);
    if (st->pending) {
        return 0;
    }
    if (pending_state_n == MAX_PENDING_STATES) {
        return luaL_error(L, "too many states waiting to be taken (%d)", MAX_PENDING_STATES);
    }
    st->pending = true;
    lua_pushvalue(L, 1);
    pending_states[pending_state_n].script = script_of(L);
    pending_states[pending_state_n].ref = luaL_ref(L, LUA_REGISTRYINDEX);
    pending_state_n++;
    savestate_capture(state_captured, NULL);
    return 0;
}

// emu.createSavestate(): a state object, filled shortly (Mesen returns a string; here, use it with loadSavestate)
static int l_create_savestate(lua_State *L)
{
    l_new_state(L);
    lua_pushcfunction(L, l_save_state);
    lua_pushvalue(L, -2);
    lua_call(L, 1, 0);
    return 1;
}

// emu.loadSavestate(state): back to that state (at the next instruction)
static int l_load_savestate(lua_State *L)
{
    state_obj *st = luaL_checkudata(L, 1, STATE_META);
    if (st->pending || st->data == NULL) {
        return luaL_error(L, "this state has not been taken yet (states are taken at the end of the picture)");
    }
    lua_pushboolean(L, savestate_load_memory(st->data, st->size));
    return 1;
}

// one.stateReady(state): has the state been taken?
static int l_state_ready(lua_State *L)
{
    state_obj *st = luaL_checkudata(L, 1, STATE_META);
    lua_pushboolean(L, !st->pending && st->data != NULL);
    return 1;
}

