// emu.stop(exitCode): end the emulation (one's exit status = exitCode)
static int l_stop(lua_State *L)
{
    exit_code = (int)luaL_optinteger(L, 1, 0);
    if (stop_hook != NULL) {
        stop_hook(exit_code);
    } else {
        cpu_request_stop();
    }
    return 0;
}

static bool make_dirs(const char *path)
{
    char buf[1024];
    snprintf(buf, sizeof(buf), "%s", path);
    for (char *p = buf + 1; *p; p++) {
        if (*p == '/' || *p == '\\') {
            char c = *p;
            *p = '\0';
#ifdef _WIN32
            _mkdir(buf);
#else
            mkdir(buf, 0755);
#endif
            *p = c;
        }
    }
#ifdef _WIN32
    return _mkdir(buf) == 0 || errno == EEXIST;
#else
    return mkdir(buf, 0755) == 0 || errno == EEXIST;
#endif
}

// emu.getScriptDataFolder(): a folder of the script's own for files it keeps (created if needed):
// $XDG_DATA_HOME/one/lua/NAME (~/.local/share/one/lua/NAME; %APPDATA%\one\lua\NAME on Windows)
static int l_get_script_data_folder(lua_State *L)
{
    script_t *s = script_of(L);
    char name[256];
    snprintf(name, sizeof(name), "%s", s->name);
    char *dot = strrchr(name, '.');
    if (dot != NULL) {
        *dot = '\0';
    }
    char folder[1024];
#ifdef _WIN32
    const char *base = getenv("APPDATA");
    snprintf(folder, sizeof(folder), "%s\\one\\lua\\%s", base ? base : ".", name);
#else
    const char *xdg = getenv("XDG_DATA_HOME");
    const char *home = getenv("HOME");
    if (xdg != NULL && xdg[0] != '\0') {
        snprintf(folder, sizeof(folder), "%s/one/lua/%s", xdg, name);
    } else {
        snprintf(folder, sizeof(folder), "%s/.local/share/one/lua/%s", home ? home : ".", name);
    }
#endif
    if (!make_dirs(folder)) {
        return luaL_error(L, "cannot create %s", folder);
    }
    lua_pushstring(L, folder);
    return 1;
}

