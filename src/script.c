// --- running scripts ---------------------------------------------------------------------------------------------

static int traceback(lua_State *L)
{
    const char *message = lua_tostring(L, 1);
    if (message != NULL && strstr(message, "\nstack traceback:") != NULL) {
        return 1; // (an error from the script's coroutine, lua/fceux.lua: it has its traceback already)
    }
    luaL_traceback(L, L, message ? message : "(error object is not a string)", 1);
    return 1;
}

// LOG_ERROR(SCRIPT, ...), and kept for script_last_error()
#define SCRIPT_ERROR(...)                                                                                              \
    do {                                                                                                               \
        snprintf(last_error, sizeof(last_error), __VA_ARGS__);                                                         \
        LOG_ERROR(SCRIPT, "%s", last_error);                                                                           \
    } while (0)

// call the function below its NARGS arguments on the stack; true: NRESULTS results are on the stack, false: the
// error is reported and the script marked failed (nothing left on the stack)
static bool call_with(script_t *s, int nargs, int nresults)
{
    lua_State *L = s->L;
    int function = lua_gettop(L) - nargs;
    lua_pushcfunction(L, traceback);
    lua_insert(L, function);
    calling++;
    bool ok = lua_pcall(L, nargs, nresults, function) == LUA_OK;
    calling--;
    if (!ok) {
        SCRIPT_ERROR("%s: %s", s->name, lua_tostring(L, -1));
        lua_pop(L, 1);
        s->failed = true;
    }
    lua_remove(L, function);
    return ok;
}

static bool call(script_t *s)
{
    return call_with(s, 0, 0);
}

static void fire(script_t *s, script_event_type type)
{
    for (int i = 0; i < MAX_CALLBACKS && !s->failed; i++) {
        int ref = s->callbacks[type][i];
        if (ref != LUA_NOREF) {
            lua_rawgeti(s->L, LUA_REGISTRYINDEX, ref);
            call(s);
        }
    }
}

static void close_script(int index)
{
    script_t *s = scripts[index];
    if (!s->failed) {
        fire(s, SCRIPT_EVENT_SCRIPT_ENDED);
    }
    LOG_INFO(SCRIPT, "%s ended", s->name);
    remove_mem_callbacks_of(s);
    forget_pending_states_of(s);
    script_window_close_all(s);
    int kept = 0;
    for (int i = 0; i < draw_n; i++) {
        if (draws[i].owner == s) {
            free_draw(&draws[i]);
        } else {
            draws[kept++] = draws[i];
        }
    }
    draw_n = kept;
    lua_close(s->L);
    free(s);
    for (int i = index; i < script_n - 1; i++) {
        scripts[i] = scripts[i + 1];
    }
    script_n--;
    script_active = script_n > 0;
    if (!script_active) { // (script_frame_done() is not called any more: take the drawings off the picture now)
        memset(hud_layer, 0, sizeof(hud_layer));
        video_set_hud(NULL);
    }
}

static void close_failed(void)
{
    for (int i = script_n - 1; i >= 0; i--) {
        if (scripts[i]->failed) {
            close_script(i);
        }
    }
}

void script_event_fire(script_event_type type)
{
    dispatch_depth++;
    for (int i = 0; i < script_n; i++) {
        if (!scripts[i]->failed) {
            fire(scripts[i], type);
        }
    }
    if (--dispatch_depth == 0) {
        close_failed();
    }
}

bool script_load(const char *path)
{
    if (script_n == MAX_SCRIPTS) {
        SCRIPT_ERROR("%s: too many scripts (%d)", path, MAX_SCRIPTS);
        return false;
    }
    script_t *s = calloc(1, sizeof(*s));
    if (s != NULL) {
        s->L = luaL_newstate();
    }
    if (s == NULL || s->L == NULL) {
        free(s);
        SCRIPT_ERROR("%s: out of memory", path);
        return false;
    }
    snprintf(s->path, sizeof(s->path), "%s", path);
    const char *slash = strrchr(path, '/');
    snprintf(s->name, sizeof(s->name), "%s", slash ? slash + 1 : path);
    for (int e = 0; e < SCRIPT_EVENTS; e++) {
        for (int i = 0; i < MAX_CALLBACKS; i++) {
            s->callbacks[e][i] = LUA_NOREF;
        }
    }
    lua_State *L = s->L;
    *(script_t **)lua_getextraspace(L) = s;
    luaL_openlibs(L);
    open_emu(L);

    // require() finds modules next to the script too
    char dir[1024];
    snprintf(dir, sizeof(dir), "%.*s", slash ? (int)(slash - path) : 1, slash ? path : ".");
    lua_getglobal(L, "package");
    lua_pushfstring(L, "%s/?.lua;", dir);
    lua_getfield(L, -2, "path");
    lua_concat(L, 2);
    lua_setfield(L, -2, "path");
    lua_pop(L, 1);

    scripts[script_n++] = s;
    script_active = true;
    // lua/fceux.lua adds FCEUX's API and returns the function that starts the script: its main chunk runs as a
    // coroutine, so an FCEUX style main loop (emu.frameadvance()) works; a Mesen style chunk simply returns
    if (luaL_loadbuffer(L, (const char *)fceux_lua, fceux_lua_size, "=fceux.lua") != LUA_OK) {
        SCRIPT_ERROR("%s", lua_tostring(L, -1));
        lua_pop(L, 1);
        s->failed = true;
    } else if (call_with(s, 0, 1)) {
        if (luaL_loadfile(L, path) != LUA_OK) {
            SCRIPT_ERROR("%s", lua_tostring(L, -1));
            lua_pop(L, 2);
            s->failed = true;
        } else {
            LOG_INFO(SCRIPT, "%s started", s->name);
            call_with(s, 1, 0); // the starter with the main chunk: registers its callbacks
        }
    }
    bool ok = !s->failed;
    if (dispatch_depth == 0) {
        close_failed();
    }
    return ok;
}

