// the arguments as print() shows them, separated by tabs
static void join_args(lua_State *L, luaL_Buffer *b)
{
    int n = lua_gettop(L);
    luaL_buffinit(L, b);
    for (int i = 1; i <= n; i++) {
        size_t len;
        const char *text = luaL_tolstring(L, i, &len);
        if (i > 1) {
            luaL_addchar(b, '\t');
        }
        luaL_addvalue(b); // (pops the string)
        (void)text;
        (void)len;
    }
}

// print(...) and emu.log(...): the log ("script" category; the console, the debugger's command window)
static int l_log(lua_State *L)
{
    luaL_Buffer b;
    join_args(L, &b);
    luaL_pushresult(&b);
    LOG_INFO(SCRIPT, "%s", lua_tostring(L, -1));
    return 0;
}

