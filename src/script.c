static void set_field(lua_State *L, const char *key, lua_Integer value)
{
    lua_pushinteger(L, value);
    lua_setfield(L, -2, key);
}

// emu.getState(): a flat table with Mesen 2's key names ("cpu.pc", "ppu.scanline", ...). The pre-render line is
// scanline -1 as in Mesen (ONE counts it as 261).
static int l_get_state(lua_State *L)
{
    lua_newtable(L);
    set_field(L, "cpu.a", cpu_debug_get_reg_a());
    set_field(L, "cpu.x", cpu_debug_get_reg_x());
    set_field(L, "cpu.y", cpu_debug_get_reg_y());
    set_field(L, "cpu.sp", cpu_debug_get_sp());
    set_field(L, "cpu.ps", cpu_debug_get_reg_p());
    set_field(L, "cpu.pc", cpu_debug_get_pc());
    set_field(L, "cpu.cycleCount", (lua_Integer)cpu_debug_get_cycle());
    uint32_t scanline = ppu_debug_get_scanline();
    set_field(L, "ppu.scanline", scanline == 261 ? -1 : (lua_Integer)scanline);
    set_field(L, "ppu.cycle", ppu_debug_get_scanline_clock());
    set_field(L, "ppu.frameCount", ppu_debug_get_frame_num());
    set_field(L, "ppu.control", ppu_get_ppuctrl());
    set_field(L, "ppu.mask", ppu_get_ppumask());
    set_field(L, "ppu.status", ppu_debug_read_regs(0x2002));
    set_field(L, "ppu.videoRamAddr", ppu_debug_get_v());
    set_field(L, "ppu.tmpVideoRamAddr", ppu_debug_get_t());
    set_field(L, "ppu.xScroll", ppu_debug_get_fine_x());
    set_field(L, "ppu.writeToggle", ppu_debug_get_w());
    set_field(L, "frameCount", ppu_debug_get_frame_num());
    return 1;
}

// emu.getRomInfo()
static int l_get_rom_info(lua_State *L)
{
    lua_newtable(L);
    const char *slash = strrchr(rom_path, '/');
#ifdef _WIN32
    const char *backslash = strrchr(rom_path, '\\');
    if (backslash != NULL && (slash == NULL || backslash > slash)) {
        slash = backslash;
    }
#endif
    lua_pushstring(L, slash ? slash + 1 : rom_path);
    lua_setfield(L, -2, "name");
    lua_pushstring(L, rom_path);
    lua_setfield(L, -2, "path");
    char crc[16];
    snprintf(crc, sizeof(crc), "%08X", (unsigned)savestate_rom_crc());
    lua_pushstring(L, crc);
    lua_setfield(L, -2, "fileCrc32Hash");
    return 1;
}

// --- events ------------------------------------------------------------------------------------------------------

static int check_event(lua_State *L, int arg)
{
    lua_Integer type = luaL_checkinteger(L, arg);
    luaL_argcheck(L, type >= 0 && type < SCRIPT_EVENTS, arg, "not an emu.eventType value");
    return (int)type;
}

// emu.addEventCallback(function, eventType) -> reference (for removeEventCallback)
static int l_add_event_callback(lua_State *L)
{
    luaL_checktype(L, 1, LUA_TFUNCTION);
    int type = check_event(L, 2);
    script_t *s = script_of(L);
    for (int i = 0; i < MAX_CALLBACKS; i++) {
        if (s->callbacks[type][i] == LUA_NOREF) {
            lua_pushvalue(L, 1);
            s->callbacks[type][i] = luaL_ref(L, LUA_REGISTRYINDEX);
            lua_pushinteger(L, s->callbacks[type][i]);
            return 1;
        }
    }
    return luaL_error(L, "too many %s callbacks (%d)", event_names[type], MAX_CALLBACKS);
}

// emu.removeEventCallback(reference, eventType)
static int l_remove_event_callback(lua_State *L)
{
    lua_Integer ref = luaL_checkinteger(L, 1);
    int type = check_event(L, 2);
    script_t *s = script_of(L);
    for (int i = 0; i < MAX_CALLBACKS; i++) {
        if (s->callbacks[type][i] == ref) {
            luaL_unref(L, LUA_REGISTRYINDEX, (int)ref);
            s->callbacks[type][i] = LUA_NOREF;
        }
    }
    return 0;
}

