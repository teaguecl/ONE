// emu.drawString(x, y, text, textColor, backgroundColor, maxWidth, duration, delay)
static int l_draw_string(lua_State *L)
{
    int x = coord(L, 1), y = coord(L, 2);
    uint32_t color = (uint32_t)luaL_optinteger(L, 4, 0xFFFFFF);
    uint32_t background = (uint32_t)luaL_optinteger(L, 5, 0xFF000000); // (transparent)
    int max_width = (int)luaL_optinteger(L, 6, 0);
    int frames = (int)luaL_optinteger(L, 7, 1), delay = (int)luaL_optinteger(L, 8, 0);
    const char *text = luaL_tolstring(L, 3, NULL); // (pushed on the stack: the arguments are read first)
    char *copy = malloc(strlen(text) + 1);
    if (copy == NULL) {
        return luaL_error(L, "out of memory (drawString)");
    }
    strcpy(copy, text); // NOLINT(clang-analyzer-security.insecureAPI.strcpy): sized above
    lua_pop(L, 1);
    draw_cmd *d = new_draw(L, DRAW_STRING, 7);
    d->frames = frames > 0 ? frames : 1;
    d->delay = delay;
    d->x = x;
    d->y = y;
    d->color = color;
    d->background = background;
    d->max_width = max_width;
    d->text = copy;
    return 0;
}

