// --- breakpoint conditions (one-debugger: bpx ... if EXPRESSION) ---------------------------------------------------
// A Lua state of their own (not a script: no events), with the emu functions. Besides globals, an expression sees
// the registers a, x, y, s, p, pc, the PPU's scanline (0-261), cycle (dot) and frame, mem[address] (a CPU read
// without side effects), and for a memory breakpoint the address and value of the access.

static script_t *conditions;

static int condition_index(lua_State *L)
{
    const char *key = lua_tostring(L, 2);
    lua_Integer value;
    if (key == NULL) {
        return 0;
    } else if (strcmp(key, "a") == 0) {
        value = cpu_debug_get_reg_a();
    } else if (strcmp(key, "x") == 0) {
        value = cpu_debug_get_reg_x();
    } else if (strcmp(key, "y") == 0) {
        value = cpu_debug_get_reg_y();
    } else if (strcmp(key, "s") == 0 || strcmp(key, "sp") == 0) {
        value = cpu_debug_get_sp();
    } else if (strcmp(key, "p") == 0) {
        value = cpu_debug_get_reg_p();
    } else if (strcmp(key, "pc") == 0) {
        value = cpu_debug_get_pc();
    } else if (strcmp(key, "scanline") == 0) {
        value = ppu_debug_get_scanline();
    } else if (strcmp(key, "cycle") == 0) {
        value = ppu_debug_get_scanline_clock();
    } else if (strcmp(key, "frame") == 0) {
        value = ppu_debug_get_frame_num();
    } else {
        return 0;
    }
    lua_pushinteger(L, value);
    return 1;
}

static int condition_mem_index(lua_State *L)
{
    lua_Integer address = luaL_checkinteger(L, 2);
    lua_pushinteger(L, cpu_debug_read((uint16_t)address));
    return 1;
}

static bool conditions_open(void)
{
    if (conditions != NULL) {
        return true;
    }
    script_t *s = calloc(1, sizeof(*s));
    if (s != NULL) {
        s->L = luaL_newstate();
    }
    if (s == NULL || s->L == NULL) {
        free(s);
        return false;
    }
    snprintf(s->name, sizeof(s->name), "breakpoint condition");
    for (int e = 0; e < SCRIPT_EVENTS; e++) {
        for (int i = 0; i < MAX_CALLBACKS; i++) {
            s->callbacks[e][i] = LUA_NOREF;
        }
    }
    lua_State *L = s->L;
    *(script_t **)lua_getextraspace(L) = s;
    luaL_openlibs(L);
    open_emu(L);
    lua_createtable(L, 0, 0); // mem[address]
    lua_createtable(L, 0, 1);
    lua_pushcfunction(L, condition_mem_index);
    lua_setfield(L, -2, "__index");
    lua_setmetatable(L, -2);
    lua_setglobal(L, "mem");
    lua_pushglobaltable(L); // registers and the PPU position: looked up when the expression runs
    lua_createtable(L, 0, 1);
    lua_pushcfunction(L, condition_index);
    lua_setfield(L, -2, "__index");
    lua_setmetatable(L, -2);
    lua_pop(L, 1);
    conditions = s;
    return true;
}

int script_condition_compile(const char *expression, char *error, size_t error_size)
{
    if (!conditions_open()) {
        snprintf(error, error_size, "out of memory");
        return -1;
    }
    lua_State *L = conditions->L;
    lua_pushfstring(L, "return (%s)", expression);
    int status = luaL_loadbuffer(L, lua_tostring(L, -1), lua_rawlen(L, -1), "=condition");
    lua_remove(L, -2);
    if (status != LUA_OK) {
        const char *message = lua_tostring(L, -1);
        const char *colon = message ? strstr(message, "condition:1: ") : NULL;
        snprintf(error, error_size, "%s", colon ? colon + 13 : (message ? message : "syntax error"));
        lua_pop(L, 1);
        return -1;
    }
    return luaL_ref(L, LUA_REGISTRYINDEX);
}

bool script_condition_eval(int handle, int address, int value)
{
    if (conditions == NULL || handle < 0) {
        return true;
    }
    lua_State *L = conditions->L;
    lua_pushinteger(L, address);
    lua_setglobal(L, "address");
    lua_pushinteger(L, value);
    lua_setglobal(L, "value");
    lua_rawgeti(L, LUA_REGISTRYINDEX, handle);
    if (!call_with(conditions, 0, 1)) {
        conditions->failed = false; // (reported; the breakpoint stops, so the error can be looked at)
        return true;
    }
    bool result = lua_toboolean(L, -1);
    lua_pop(L, 1);
    return result;
}

void script_condition_free(int handle)
{
    if (conditions != NULL && handle >= 0) {
        luaL_unref(conditions->L, LUA_REGISTRYINDEX, handle);
    }
}
