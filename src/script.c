void script_frame_done(void)
{
    static bool layer_used = false;
    if (draw_n == 0) {
        if (layer_used) {
            memset(hud_layer, 0, sizeof(hud_layer));
            layer_used = false;
        }
        video_set_hud(NULL);
        return;
    }
    layer_used = true;
    memset(hud_layer, 0, sizeof(hud_layer)); // (headless too: tests read it with one.hudPixel())
    int kept = 0;
    for (int i = 0; i < draw_n; i++) {
        draw_cmd *d = &draws[i];
        if (d->delay > 0) {
            d->delay--;
        } else {
            {
                switch (d->type) {
                case DRAW_PIXEL: plot(d->x, d->y, layer_color(d->color)); break;
                case DRAW_LINE: draw_line(d->x, d->y, d->x2, d->y2, layer_color(d->color)); break;
                case DRAW_RECT: draw_rect(d->x, d->y, d->x2, d->y2, layer_color(d->color), d->fill); break;
                case DRAW_STRING:
                    draw_string(d->x, d->y, d->text, layer_color(d->color), layer_color(d->background), d->max_width);
                    break;
                case DRAW_SCREEN:
                    for (int p = 0; p < HUD_W * HUD_H; p++) {
                        plot(p % HUD_W, p / HUD_W, layer_color(d->pixels[p]));
                    }
                    break;
                default: break;
                }
            }
            d->frames--;
        }
        if (d->frames > 0) {
            draws[kept++] = *d;
        } else {
            free_draw(d);
        }
    }
    draw_n = kept;
    video_set_hud(hud_layer);
}

