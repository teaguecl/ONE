// Mesen 2's drawing functions: commands kept with a duration (frames) and a delay, drawn into a 256x240 layer over
// the picture at the end of each frame (video_set_hud()). Colors are Mesen's: 0xAARRGGBB with the alpha inverted
// (0x00 = opaque, 0xFF = invisible), so 0xFF0000 is opaque red and 0x80FF0000 half-transparent red.

#define HUD_W 256
#define HUD_H 240

enum { DRAW_PIXEL, DRAW_LINE, DRAW_RECT, DRAW_STRING, DRAW_SCREEN };

typedef struct {
    int type;
    int x, y, x2, y2; // (rectangle: x2, y2 = width, height)
    uint32_t color, background;
    bool fill;
    int max_width;
    char *text;        // DRAW_STRING
    uint32_t *pixels;  // DRAW_SCREEN: a whole picture
    int frames;        // still to draw
    int delay;         // frames to wait first
    const void *owner; // the script that drew it (its drawings go when it ends)
} draw_cmd;

static draw_cmd *draws = NULL;
static int draw_n = 0, draw_cap = 0;
static uint32_t hud_layer[HUD_W * HUD_H];

// Mesen color -> layer color (alpha 255 = opaque)
static uint32_t layer_color(uint32_t mesen)
{
    return ((255u - (mesen >> 24)) << 24) | (mesen & 0xFFFFFFu);
}

static void plot(int x, int y, uint32_t c)
{
    if (x < 0 || y < 0 || x >= HUD_W || y >= HUD_H || (c >> 24) == 0) {
        return;
    }
    uint32_t *p = &hud_layer[y * HUD_W + x];
    uint32_t a = c >> 24;
    if (a == 255 || (*p >> 24) == 0) {
        *p = c;
        return;
    }
    // c over what is already drawn there
    uint32_t b = *p, ab = b >> 24;
    uint32_t out_a = a + ab * (255 - a) / 255;
    uint32_t r = (((c >> 16) & 0xFF) * a + ((b >> 16) & 0xFF) * (255 - a)) / 255;
    uint32_t g = (((c >> 8) & 0xFF) * a + ((b >> 8) & 0xFF) * (255 - a)) / 255;
    uint32_t bl = ((c & 0xFF) * a + (b & 0xFF) * (255 - a)) / 255;
    *p = (out_a << 24) | (r << 16) | (g << 8) | bl;
}

static void draw_line(int x0, int y0, int x1, int y1, uint32_t c)
{
    int dx = abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
    int dy = -abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;
    for (int guard = 0; guard < 4096; guard++) {
        plot(x0, y0, c);
        if (x0 == x1 && y0 == y1) {
            break;
        }
        int e2 = 2 * err;
        if (e2 >= dy) {
            err += dy;
            x0 += sx;
        }
        if (e2 <= dx) {
            err += dx;
            y0 += sy;
        }
    }
}

static void draw_rect(int x, int y, int w, int h, uint32_t c, bool fill)
{
    if (w <= 0 || h <= 0) {
        return;
    }
    for (int j = 0; j < h; j++) {
        for (int i = 0; i < w; i++) {
            if (fill || j == 0 || j == h - 1 || i == 0 || i == w - 1) {
                plot(x + i, y + j, c);
            }
        }
    }
}

// Text in the 5x7 font, 6x9 pixels per character on its background; '\n' starts a new line; max_width (pixels,
// 0 = none) wraps long lines
static void draw_string(int x, int y, const char *text, uint32_t c, uint32_t bg, int max_width)
{
    int cx = x, cy = y;
    for (const char *p = text; *p != '\0'; p++) {
        if (*p == '\n' || (max_width > 0 && cx + 6 > x + max_width)) {
            cx = x;
            cy += 9;
            if (*p == '\n') {
                continue;
            }
        }
        unsigned char ch = (unsigned char)*p;
        if (ch < 32 || ch > 126) {
            ch = '?';
        }
        draw_rect(cx, cy, 6, 9, bg, true);
        for (int row = 0; row < 7; row++) {
            for (int col = 0; col < 5; col++) {
                if (font5x7[ch - 32][row] & (0x10 >> col)) {
                    plot(cx + col, cy + 1 + row, c);
                }
            }
        }
        cx += 6;
    }
}

static void free_draw(draw_cmd *d)
{
    free(d->text);
    free(d->pixels);
}

static draw_cmd *new_draw(lua_State *L, int type, int duration_arg)
{
    if (draw_n == draw_cap) {
        int cap = draw_cap ? draw_cap * 2 : 64;
        draw_cmd *grown = realloc(draws, (size_t)cap * sizeof(*draws));
        if (grown == NULL) {
            luaL_error(L, "out of memory (drawings)");
            return NULL; // (not reached: luaL_error does not return)
        }
        draws = grown;
        draw_cap = cap;
    }
    draw_cmd *d = &draws[draw_n++];
    memset(d, 0, sizeof(*d));
    d->type = type;
    d->owner = script_of(L);
    d->frames = (int)luaL_optinteger(L, duration_arg, 1);
    d->delay = (int)luaL_optinteger(L, duration_arg + 1, 0);
    if (d->frames <= 0) {
        d->frames = 1;
    }
    return d;
}

static int coord(lua_State *L, int arg)
{
    return (int)luaL_checknumber(L, arg); // (Lua numbers: 10.5 draws at 10)
}

// emu.drawPixel(x, y, color, duration, delay)
