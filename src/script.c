// emu.getInput(port): {a=, b=, select=, start=, up=, down=, left=, right=} (booleans)
static int l_get_input(lua_State *L)
{
    int port = check_port(L, 1);
    if (port == 1 && input_zapper_present()) {
        // a Zapper on port 2: {trigger=, x=, y=} as Mesen's getInput gives it (x and y -1 when it points away from the screen)
        input_zapper_state aim;
        input_zapper_aim(&aim);
        lua_createtable(L, 0, 3);
        lua_pushboolean(L, aim.trigger);
        lua_setfield(L, -2, "trigger");
        set_field(L, "x", aim.on_screen ? aim.x : -1);
        set_field(L, "y", aim.on_screen ? aim.y : -1);
        return 1;
    }
    uint8_t buttons = input_buttons(port);
    lua_createtable(L, 0, 8);
    for (int b = 0; b < 8; b++) {
        lua_pushboolean(L, (buttons >> b) & 1);
        lua_setfield(L, -2, button_names[b]);
    }
    return 1;
}

// emu.setInput(input, port): the buttons the game reads this frame (call it from an inputPolled callback); buttons
// the table does not name keep the player's state
static int l_set_input(lua_State *L)
{
    luaL_checktype(L, 1, LUA_TTABLE);
    int port = check_port(L, 2);
    if (port == 1) {
        // the Zapper (port 2): {x=, y=, trigger=}; what the table does not name keeps the present aim. x or y outside the
        // picture (or -1) = pointing away from the screen. (Mesen 2.2.1 ignores this for its Zapper; ONE does not.)
        lua_getfield(L, 1, "x");
        bool has_x = lua_isnumber(L, -1);
        lua_Number x = lua_tonumber(L, -1);
        lua_getfield(L, 1, "y");
        bool has_y = lua_isnumber(L, -1);
        lua_Number y = lua_tonumber(L, -1);
        lua_getfield(L, 1, "trigger");
        bool has_trigger = !lua_isnil(L, -1);
        bool trigger = lua_toboolean(L, -1);
        lua_pop(L, 3);
        if (has_x || has_y || has_trigger) {
            input_zapper_state aim = {false, 0, 0, false};
            input_zapper_aim(&aim);
            if (has_x) {
                aim.x = (int)x;
            }
            if (has_y) {
                aim.y = (int)y;
            }
            if (has_x || has_y) {
                aim.on_screen = aim.x >= 0 && aim.x < VIDEO_WIDTH && aim.y >= 0 && aim.y < VIDEO_HEIGHT;
            }
            if (has_trigger) {
                aim.trigger = trigger;
            }
            input_set_zapper_frame(&aim);
            return 0;
        }
    }
    uint8_t buttons = input_buttons(port);
    for (int b = 0; b < 8; b++) {
        lua_getfield(L, 1, button_names[b]);
        if (!lua_isnil(L, -1)) {
            buttons = lua_toboolean(L, -1) ? (uint8_t)(buttons | (1u << b)) : (uint8_t)(buttons & ~(1u << b));
        }
        lua_pop(L, 1);
    }
    input_set_override(port, buttons);
    return 0;
}

