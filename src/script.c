// Mesen 2's emu.memType names. The values are ONE's own; scripts use the names.
enum {
    MEM_NES,          // nesMemory: the CPU address space
    MEM_PPU,          // nesPpuMemory: the PPU address space
    MEM_PRG_ROM,      // nesPrgRom
    MEM_INTERNAL_RAM, // nesInternalRam ($0000-$07FF)
    MEM_WORK_RAM,     // nesWorkRam (cartridge RAM at $6000)
    MEM_SAVE_RAM,     // nesSaveRam (the same RAM when battery-backed)
    MEM_SPRITE_RAM,   // nesSpriteRam (OAM)
    MEM_SECONDARY_SPRITE_RAM,
    MEM_PALETTE_RAM, // nesPaletteRam
    MEM_CHR_ROM,     // nesChrRom
    MEM_CHR_RAM,     // nesChrRam
    MEM_TYPES
};
static const char *const mem_type_names[MEM_TYPES] = {
    "nesMemory",    "nesPpuMemory",          "nesPrgRom",     "nesInternalRam", "nesWorkRam", "nesSaveRam",
    "nesSpriteRam", "nesSecondarySpriteRam", "nesPaletteRam", "nesChrRom",      "nesChrRam",
};
static const char *const event_names[SCRIPT_EVENTS] = {
    "reset",       "nmi",         "irq",        "startFrame",  "endFrame",
    "inputPolled", "stateLoaded", "stateSaved", "scriptEnded", "codeBreak",
};

static script_t *script_of(lua_State *L)
{
    return *(script_t **)lua_getextraspace(L);
}

// --- memory ------------------------------------------------------------------------------------------------------

static uint8_t mem_read(int type, uint32_t address)
{
    size_t size = 0;
    const uint8_t *data = NULL;
    switch (type) {
    case MEM_NES: return cpu_debug_read((uint16_t)address); // (no side effects: reading $2002 does not clear VBL)
    case MEM_PPU: return ppu_debug_read((uint16_t)(address & 0x3FFF));
    case MEM_PRG_ROM: data = mapper_debug_prg_rom(&size); break;
    case MEM_INTERNAL_RAM: return cpu_debug_read((uint16_t)(address & 0x7FF));
    case MEM_WORK_RAM:
    case MEM_SAVE_RAM: data = mapper_debug_prg_ram(&size); break;
    case MEM_SPRITE_RAM: return ppu_debug_read_oam((uint8_t)address);
    case MEM_SECONDARY_SPRITE_RAM: return ppu_debug_read_oam2((uint8_t)address);
    case MEM_PALETTE_RAM: return ppu_debug_read_palette((uint8_t)address);
    case MEM_CHR_ROM: data = mapper_debug_chr_rom(&size); break;
    case MEM_CHR_RAM: return mapper_debug_read_chr((uint16_t)(address & 0x1FFF));
    default: break;
    }
    return (data != NULL && address < size) ? data[address] : 0;
}

// false: that memory cannot be written (ROM, registers through nesMemory)
static bool mem_write(int type, uint32_t address, uint8_t value)
{
    size_t size = 0;
    uint8_t *ram;
    switch (type) {
    case MEM_NES: return cpu_debug_write((uint16_t)address, value); // internal RAM and cartridge RAM
    case MEM_INTERNAL_RAM: return cpu_debug_write((uint16_t)(address & 0x7FF), value);
    case MEM_WORK_RAM:
    case MEM_SAVE_RAM:
        ram = mapper_debug_prg_ram(&size);
        if (ram == NULL || address >= size) {
            return false;
        }
        ram[address] = value;
        return true;
    case MEM_SPRITE_RAM: ppu_debug_write_oam((uint8_t)address, value); return true;
    case MEM_SECONDARY_SPRITE_RAM: ppu_debug_write_oam2((uint8_t)address, value); return true;
    case MEM_PALETTE_RAM: ppu_debug_write_palette((uint8_t)address, value); return true;
    default: return false;
    }
}

static int check_mem_type(lua_State *L, int arg)
{
    lua_Integer type = luaL_optinteger(L, arg, MEM_NES);
    luaL_argcheck(L, type >= 0 && type < MEM_TYPES, arg, "not an emu.memType value");
    return (int)type;
}

// emu.read(address, memType, signed)
static int l_read(lua_State *L)
{
    uint32_t address = (uint32_t)luaL_checkinteger(L, 1);
    int type = check_mem_type(L, 2);
    uint8_t value = mem_read(type, address);
    lua_pushinteger(L, lua_toboolean(L, 3) ? (lua_Integer)(int8_t)value : (lua_Integer)value);
    return 1;
}

// emu.readWord(address, memType, signed): little-endian
static int l_read_word(lua_State *L)
{
    uint32_t address = (uint32_t)luaL_checkinteger(L, 1);
    int type = check_mem_type(L, 2);
    uint16_t value = (uint16_t)(mem_read(type, address) | (mem_read(type, address + 1) << 8));
    lua_pushinteger(L, lua_toboolean(L, 3) ? (lua_Integer)(int16_t)value : (lua_Integer)value);
    return 1;
}

static void write_or_complain(lua_State *L, int type, uint32_t address, uint8_t value)
{
    if (!mem_write(type, address, value)) {
        script_t *s = script_of(L);
        LOG_ONCE(SCRIPT, LOG_LEVEL_WARN, "%s: emu.write to %s $%04X ignored (not writable memory)", s->name,
                 mem_type_names[type], (unsigned)address);
    }
}

// emu.write(address, value, memType)
static int l_write(lua_State *L)
{
    uint32_t address = (uint32_t)luaL_checkinteger(L, 1);
    uint8_t value = (uint8_t)luaL_checkinteger(L, 2);
    write_or_complain(L, check_mem_type(L, 3), address, value);
    return 0;
}

// emu.writeWord(address, value, memType)
static int l_write_word(lua_State *L)
{
    uint32_t address = (uint32_t)luaL_checkinteger(L, 1);
    uint16_t value = (uint16_t)luaL_checkinteger(L, 2);
    int type = check_mem_type(L, 3);
    write_or_complain(L, type, address, (uint8_t)value);
    write_or_complain(L, type, address + 1, (uint8_t)(value >> 8));
    return 0;
}

