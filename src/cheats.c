#define DIR_SIZE 1040 // ONE's config directory (1024) and "/cheats"

static void cheats_dir(char *buf, size_t size)
{
    char dir[1024];
    settings_user_dir(dir, sizeof(dir));
    snprintf(buf, size, "%s/cheats", dir);
}

// The game's file: the one in the cheats directory whose name ends in "[CRC].cht" (whatever the ROM is called now),
// else a new name: the ROM's file name without its extension, and the CRC
static void find_file(const char *rom_filename)
{
    char dir[DIR_SIZE];
    cheats_dir(dir, sizeof(dir));
    char suffix[24];
    snprintf(suffix, sizeof(suffix), "[%08X].cht", game_crc);
#ifndef _WIN32
    DIR *d = opendir(dir);
    if (d != NULL) {
        struct dirent *de;
        while ((de = readdir(d)) != NULL) {
            size_t len = strlen(de->d_name), slen = strlen(suffix);
            if (len >= slen && strcmp(de->d_name + len - slen, suffix) == 0) {
                snprintf(file, sizeof(file), "%s/%s", dir, de->d_name);
                closedir(d);
                return;
            }
        }
        closedir(d);
    }
#else
    char pattern[DIR_SIZE + 64];
    snprintf(pattern, sizeof(pattern), "%s/*%s", dir, suffix);
    WIN32_FIND_DATAA found;
    HANDLE h = FindFirstFileA(pattern, &found);
    if (h != INVALID_HANDLE_VALUE) {
        snprintf(file, sizeof(file), "%s/%s", dir, found.cFileName);
        FindClose(h);
        return;
    }
#endif
    // a new file: named after the game as the database knows it, else after the ROM file
    char name[256];
    if (db_game[0] != '\0') {
        snprintf(name, sizeof(name), "%s", db_game);
        for (char *c = name; *c != '\0'; c++) {
            if (strchr("/\\:*?\"<>|", *c) != NULL) {
                *c = '_'; // (characters file systems refuse)
            }
        }
    } else {
        const char *base = strrchr(rom_filename, '/');
        base = (base != NULL) ? base + 1 : rom_filename;
        snprintf(name, sizeof(name), "%s", base);
        char *dot = strrchr(name, '.');
        if (dot != NULL) {
            *dot = '\0';
        }
    }
    snprintf(file, sizeof(file), "%s/%s %s", dir, name, suffix);
}

// "  key = value" -> key, value (quotes taken off); false for blank lines and comments
static bool parse_line(char *line, char **key, char **value)
{
    char *eq = strchr(line, '=');
    while (*line == ' ' || *line == '\t') {
        line++;
    }
    if (*line == '#' || *line == '\0' || eq == NULL) {
        return false;
    }
    char *k_end = eq;
    while (k_end > line && (k_end[-1] == ' ' || k_end[-1] == '\t')) {
        k_end--;
    }
    *k_end = '\0';
    char *v = eq + 1;
    while (*v == ' ' || *v == '\t') {
        v++;
    }
    size_t len = strcspn(v, "\r\n");
    v[len] = '\0';
    while (len > 0 && (v[len - 1] == ' ' || v[len - 1] == '\t')) {
        v[--len] = '\0';
    }
    if (len >= 2 && v[0] == '"' && v[len - 1] == '"') {
        v[len - 1] = '\0';
        v++;
    }
    *key = line;
    *value = v;
    return true;
}

static void load_file(void)
{
    FILE *f = fopen(file, "r");
    if (f == NULL) {
        return; // (a game never set up: empty list, Game Genie off)
    }
    char line[512];
    while (fgets(line, sizeof(line), f) != NULL) {
        char *key, *value;
        if (!parse_line(line, &key, &value)) {
            continue;
        }
        int n;
        char field[16];
        if (strcmp(key, "gamegenie_enabled") == 0) {
            enabled = (strcmp(value, "true") == 0);
        } else if (sscanf(key, "cheat%d_%15s", &n, field) == 2 && n >= 0 && n < CHEATS_MAX) {
            while (entry_count <= n) {
                memset(&entries[entry_count++], 0, sizeof(entries[0]));
            }
            if (strcmp(field, "desc") == 0) {
                set_description(&entries[n], value);
            } else if (strcmp(field, "code") == 0 && !cheats_decode(value, &entries[n].code)) {
                LOG_WARN(MAPPER, "%s: cheat%d_code is not a Game Genie code: %s", file, n, value);
            } else if (strcmp(field, "enable") == 0) {
                entries[n].on = (strcmp(value, "true") == 0);
            }
        }
    }
    fclose(f);
    // drop entries without a valid code (other cheat kinds, gaps in the numbering)
    int kept = 0;
    for (int i = 0; i < entry_count; i++) {
        if (entries[i].code.address >= 0x8000) {
            entries[kept++] = entries[i];
        }
    }
    entry_count = kept;
    LOG_INFO(MAPPER, "Game Genie: %d code%s for this game (%s), %s", entry_count, entry_count == 1 ? "" : "s", file,
             enabled ? "on" : "off");
}

static void save_file(void)
{
    if (!persistent || file[0] == '\0') {
        return;
    }
    settings_make_parent_dirs(file);
    char tmp[sizeof(file) + 8];
    snprintf(tmp, sizeof(tmp), "%s.tmp", file);
    FILE *f = fopen(tmp, "w");
    if (f == NULL) {
        LOG_WARN(MAPPER, "cannot write %s", tmp);
        return;
    }
    const char *base = strrchr(game, '/');
    fprintf(f, "# ONE: Game Genie codes for %s (No-Intro CRC-32 %08X)\n", base != NULL ? base + 1 : game, game_crc);
    fprintf(f, "gamegenie_enabled = %s\ncheats = %d\n", enabled ? "true" : "false", entry_count);
    for (int i = 0; i < entry_count; i++) {
        char text[9];
        cheats_encode(&entries[i].code, text);
        fprintf(f, "\ncheat%d_desc = \"%s\"\ncheat%d_code = \"%s\"\ncheat%d_enable = %s\n", i, entries[i].description,
                i, text, i, entries[i].on ? "true" : "false");
    }
    bool written = fclose(f) == 0;
    if (written) {
        remove(file); // (rename() does not replace a file on Windows)
        written = rename(tmp, file) == 0;
    }
    if (!written) {
        LOG_WARN(MAPPER, "cannot write %s", file);
        remove(tmp);
    }
}

// --- the code database ------------------------------------------------------------------------------------------

// The database file the user may have added (cheats.h): read once, with a newline in front so that every game's
// "@<SHA1> <name>" line is found the same way. NULL when there is none.
static char *user_db_text = NULL; // (not part of a save state)
static bool user_db_tried = false;

static const char *user_db(void)
{
    if (user_db_tried) {
        return user_db_text;
    }
    user_db_tried = true;
    char dir[DIR_SIZE], path[DIR_SIZE + 32];
    cheats_dir(dir, sizeof(dir));
    snprintf(path, sizeof(path), "%s/nes_gamegenie.txt", dir);
    FILE *f = fopen(path, "rb");
    if (f == NULL) {
        return NULL;
    }
    fseek(f, 0, SEEK_END);
    long size = ftell(f);
    fseek(f, 0, SEEK_SET);
    if (size > 0 && size < (64L << 20)) {
        user_db_text = malloc((size_t)size + 2);
        if (user_db_text != NULL) {
            user_db_text[0] = '\n';
            size_t got = fread(user_db_text + 1, 1, (size_t)size, f);
            user_db_text[got + 1] = '\0';
        }
    }
    fclose(f);
    return user_db_text;
}

// The game's block in a database text: "@<SHA1> <name>" then one entry per line ("codes<TAB>description")
static bool db_find_in(const char *text, const char *key)
{
    const char *at = (text != NULL) ? strstr(text, key) : NULL;
    if (at == NULL) {
        return false;
    }
    const char *name = at + strlen(key);
    const char *eol = strchr(name, '\n');
    if (eol == NULL) {
        return false;
    }
    snprintf(db_game, sizeof(db_game), "%.*s", (int)(eol - name) - (eol > name && eol[-1] == '\r' ? 1 : 0), name);
    db_first = eol + 1;
    for (const char *line = db_first; *line != '\0' && *line != '@';) {
        db_entries++;
        const char *next = strchr(line, '\n');
        line = (next != NULL) ? next + 1 : line + strlen(line);
    }
    return true;
}

// The user's database first, then the one built in
static void db_find(const char *sha1)
{
    db_game[0] = '\0';
    db_first = NULL;
    db_entries = 0;
    if (sha1 == NULL || strlen(sha1) != 40) {
        return;
    }
    char key[44];
    snprintf(key, sizeof(key), "\n@%s ", sha1);
    if (!db_find_in(user_db(), key)) {
        db_find_in((const char *)gamegenie_db, key);
    }
}

const char *cheats_db_game(void)
{
    return db_game;
}

int cheats_db_count(void)
{
    return db_entries;
}

bool cheats_db_get(int index, char *codes, int codes_size, char *description, int description_size)
{
    if (index < 0 || index >= db_entries) {
        return false;
    }
    const char *line = db_first;
    for (int i = 0; i < index; i++) {
        line = strchr(line, '\n') + 1;
    }
    const char *eol = strchr(line, '\n');
    if (eol == NULL) {
        eol = line + strlen(line);
    }
    if (eol > line && eol[-1] == '\r') {
        eol--; // (a database file with Windows line ends)
    }
    const char *tab = memchr(line, '\t', (size_t)(eol - line));
    if (tab == NULL) {
        tab = eol;
    }
    snprintf(codes, (size_t)codes_size, "%.*s", (int)(tab - line), line);
    snprintf(description, (size_t)description_size, "%.*s", tab < eol ? (int)(eol - tab - 1) : 0,
             tab < eol ? tab + 1 : "");
    return true;
}

int cheats_db_add(int index)
{
    char codes[128], description[CHEATS_DESC_SIZE];
    if (!cheats_db_get(index, codes, sizeof(codes), description, sizeof(description))) {
        return 0;
    }
    int parts = 1;
    for (const char *c = codes; *c != '\0'; c++) {
        parts += (*c == '+') ? 1 : 0;
    }
    int added = 0, part = 0;
    char *one = codes;
    while (one != NULL) {
        char *rest = strchr(one, '+');
        if (rest != NULL) {
            *rest++ = '\0';
        }
        part++;
        char desc[CHEATS_DESC_SIZE + 32];
        if (parts > 1) {
            snprintf(desc, sizeof(desc), "%s (%d/%d)", description, part, parts); // (they work together)
        } else {
            snprintf(desc, sizeof(desc), "%s", description);
        }
        cheat_code code;
        if (cheats_decode(one, &code) && cheats_add(&code, desc)) {
            added++;
        }
        one = rest;
    }
    return added;
}

void cheats_set_game(const char *rom_filename, uint32_t crc, const char *sha1)
{
    db_find(sha1);
    bool same_game = (game[0] != '\0') && (crc == game_crc);
    bool first = (game[0] == '\0');
    snprintf(game, sizeof(game), "%s", rom_filename);
    game_crc = crc;
    if (same_game) {
        return; // a power cycle: the list stays
    }
    if (!first) {
        entry_count = 0; // the list was the previous game's
        enabled = false;
    }
    file[0] = '\0';
    if (persistent) {
        find_file(rom_filename);
        entry_count = 0;
        enabled = false;
        load_file();
    }
    bool keep_persistent = persistent;
    persistent = false; // (nothing changed: no need to write the file back)
    changed();
    persistent = keep_persistent;
}

// A read of ADDRESS that found ROM_VALUE in the ROM: the code for it, if there is one (the first that matches)
uint8_t cheats_patch(uint16_t address, uint8_t rom_value)
{
    if (address < 0x8000 || page_has_code[(address >> 8) & 0x7F] == 0) {
        return rom_value;
    }
    for (int i = 0; i < entry_count; i++) {
        const cheat_code *c = &entries[i].code;
        if (entries[i].on && c->address == address && (!c->has_compare || c->compare == rom_value)) {
            return c->value;
        }
    }
    return rom_value;
}

void cheats_state(state_io *io)
{
    (void)io;
    // not machine state: the player's choice, kept across loads (gamegenie_plan.md)
    STATE_SKIP(cheats_active);
    STATE_SKIP(entries);
    STATE_SKIP(entry_count);
    STATE_SKIP(enabled);
    STATE_SKIP(page_has_code);
    STATE_SKIP(game);
    STATE_SKIP(game_crc);
    STATE_SKIP(persistent);
    STATE_SKIP(file);
    STATE_SKIP(db_game);
    STATE_SKIP(user_db_text);
    STATE_SKIP(user_db_tried);
    STATE_SKIP(db_first);
    STATE_SKIP(db_entries);
}
