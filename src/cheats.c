bool cheats_active = false;             // Game Genie on and at least one code ticked: mapper.c tests only this
static cheat_entry entries[CHEATS_MAX]; // the game's list, in the order the codes were added
static int entry_count = 0;             //
static bool enabled = false;            // Game Genie on for this game (off until a code is ticked)
static uint8_t page_has_code[0x80];     // per 256-byte page of $8000-$FFFF: how many ticked codes are there
static char game[1024] = "";            // the ROM the list belongs to ("" = none yet)
static uint32_t game_crc = 0;           // its No-Intro CRC-32
static bool persistent = false;         // cheats_set_persistent()
static char file[1400] = "";            // the game's file while persistent ("" = none)
static char db_game[200] = "";          // the game's No-Intro name in the code database ("" = not there)
static const char *db_first = NULL;     // its first entry line in the database text
static int db_entries = 0;              // its entries

static const char letters[] = "APZLGITYEOXUKSVN"; // letter i encodes the 4-bit value i

bool cheats_decode(const char *text, cheat_code *code)
{
    int n[8];
    size_t len = 0;
    for (const char *c = text; *c != '\0'; c++) {
        if (*c == '-' || *c == ' ') {
            continue; // "SXI-OPO" style separators
        }
        const char *p = strchr(letters, toupper((unsigned char)*c));
        if (p == NULL || len == 8) {
            return false;
        }
        n[len++] = (int)(p - letters);
    }
    if (len != 6 && len != 8) {
        return false;
    }
    code->address = (uint16_t)(0x8000 | ((n[3] & 7) << 12) | ((n[5] & 7) << 8) | ((n[4] & 8) << 8) | ((n[2] & 7) << 4) |
                               ((n[1] & 8) << 4) | (n[4] & 7) | (n[3] & 8));
    code->has_compare = (len == 8);
    if (len == 6) {
        code->value = (uint8_t)(((n[1] & 7) << 4) | ((n[0] & 8) << 4) | (n[0] & 7) | (n[5] & 8));
        code->compare = 0;
    } else {
        code->value = (uint8_t)(((n[1] & 7) << 4) | ((n[0] & 8) << 4) | (n[0] & 7) | (n[7] & 8));
        code->compare = (uint8_t)(((n[7] & 7) << 4) | ((n[6] & 8) << 4) | (n[6] & 7) | (n[5] & 8));
    }
    return true;
}

void cheats_encode(const cheat_code *code, char text[9])
{
    const unsigned a = code->address, d = code->value;
    const bool eight = code->has_compare;
    const unsigned c = eight ? code->compare : 0;
    int n[8];
    n[0] = (int)(((d >> 4) & 8) | (d & 7));
    n[1] = (int)(((a >> 4) & 8) | ((d >> 4) & 7));
    n[2] = (int)((eight ? 8 : 0) | ((a >> 4) & 7)); // the third letter's top bit marks an 8-letter code
    n[3] = (int)((a & 8) | ((a >> 12) & 7));
    n[4] = (int)(((a >> 8) & 8) | (a & 7));
    n[5] = (int)(((eight ? c : d) & 8) | ((a >> 8) & 7));
    n[6] = (int)(((c >> 4) & 8) | (c & 7));
    n[7] = (int)((d & 8) | ((c >> 4) & 7));
    int len = eight ? 8 : 6;
    for (int i = 0; i < len; i++) {
        text[i] = letters[n[i]];
    }
    text[len] = '\0';
}

static bool same_code(const cheat_code *a, const cheat_code *b)
{
    return a->address == b->address && a->value == b->value && a->has_compare == b->has_compare &&
           (!a->has_compare || a->compare == b->compare);
}

static void save_file(void);

// After any change: what the read path applies, and the game's file
static void changed(void)
{
    memset(page_has_code, 0, sizeof(page_has_code));
    int ticked = 0;
    for (int i = 0; i < entry_count; i++) {
        if (entries[i].on) {
            page_has_code[(entries[i].code.address >> 8) & 0x7F]++;
            ticked++;
        }
    }
    cheats_active = enabled && ticked > 0;
    mapper_update_cheats(); // (reads are patched only while a code is on)
    save_file();
}

int cheats_count(void)
{
    return entry_count;
}

const cheat_entry *cheats_get(int index)
{
    return (index >= 0 && index < entry_count) ? &entries[index] : NULL;
}

int cheats_find(const cheat_code *code)
{
    for (int i = 0; i < entry_count; i++) {
        if (same_code(&entries[i].code, code)) {
            return i;
        }
    }
    return -1;
}

static void set_description(cheat_entry *e, const char *description)
{
    if (description != NULL && description[0] != '\0') {
        snprintf(e->description, sizeof(e->description), "%.*s", (int)sizeof(e->description) - 1, description);
        for (char *c = e->description; *c != '\0'; c++) {
            if (*c == '"' || *c == '\n' || *c == '\r') {
                *c = '\''; // (the file keeps it between double quotes, on one line)
            }
        }
    }
}

bool cheats_add(const cheat_code *code, const char *description)
{
    if (code->address < 0x8000) {
        return false;
    }
    int i = cheats_find(code);
    if (i < 0) {
        if (entry_count == CHEATS_MAX) {
            return false;
        }
        i = entry_count++;
        memset(&entries[i], 0, sizeof(entries[i]));
        entries[i].code = *code;
    }
    set_description(&entries[i], description);
    entries[i].on = true;
    enabled = true; // (ticking a code is what a player means by "use it")
    changed();
    return true;
}

void cheats_set_on(int index, bool on)
{
    if (index >= 0 && index < entry_count) {
        entries[index].on = on;
        if (on) {
            enabled = true;
        }
        changed();
    }
}

void cheats_delete(int index)
{
    if (index >= 0 && index < entry_count) {
        memmove(&entries[index], &entries[index + 1], (size_t)(entry_count - index - 1) * sizeof(entries[0]));
        entry_count--;
        changed();
    }
}

void cheats_clear(void)
{
    entry_count = 0;
    changed();
}

void cheats_set_enabled(bool on)
{
    enabled = on;
    changed();
}

bool cheats_enabled(void)
{
    return enabled;
}

int cheats_active_count(void)
{
    int n = 0;
    for (int i = 0; i < entry_count; i++) {
        n += entries[i].on ? 1 : 0;
    }
    return n;
}

