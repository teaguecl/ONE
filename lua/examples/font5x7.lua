local function text(pixels, width, height, x, y, s, color)
  for i = 1, #s do
    local glyph = FONT[s:byte(i) - 31]
    if glyph then
      for row = 0, 6 do
        local bits = glyph[row + 1]
        for col = 0, 4 do
          local px, py = x + col, y + row
          if (bits >> (4 - col)) & 1 ~= 0 and px >= 0 and py >= 0 and px < width and py < height then
            pixels[py * width + px + 1] = color
          end
        end
      end
    end
    x = x + 6
  end
end

return { glyphs = FONT, text = text }
