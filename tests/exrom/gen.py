"""Makes the test ROM and --batch script of the MMC5 (ExROM, mapper 5; tests/CMakeLists.txt, debugger_mapper_exrom).
Run: python3 gen.py  (writes exrom.nes and exrom.txt next to this file).

The ROM is an iNES 1.0 file (so the PRG-RAM is the 64KB default): 128KB PRG-ROM as sixteen 8KB banks, 64KB CHR-ROM as
sixty-four 1KB banks.  Bank b of PRG starts with the marker $B0+b; 1KB CHR bank n starts with the byte n.  Every PRG bank
holds the same program (at offset $20 of the slot at $E000, after the reset code at $0D that waits for two vblanks, and the IRQ routine at $600), so the code
runs whichever bank is at $E000.  The script runs two frames (the PPU warm-up), sets the PC, then steps through the program
with `t` and asserts what the CPU and the PPU see: the four PRG modes, ROM / RAM banks and the RAM protection, the four CHR
modes with sets A and B, the name table sources of $5105 (CIRAM, ExRAM, fill mode), ExRAM, the multiplier, and the
scanline IRQ (when it comes, and how many)."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = 0xE000  # the slot at $E000: the program is at BASE+$20, the IRQ routine at BASE+$600


def lda(v):
    return bytes([0xA9, v & 0xFF])


def sta(a):
    return bytes([0x8D, a & 0xFF, a >> 8])


def lda_abs(a):
    return bytes([0xAD, a & 0xFF, a >> 8])


def inc_abs(a):
    return bytes([0xEE, a & 0xFF, a >> 8])


CLI = bytes([0x58])
JMP_SELF = bytes([0x4C, 0x00, 0x00])  # (address filled in by the program builder)


class Prog:
    def __init__(self):
        self.code = b""
        self.script = ["# generated by gen.py (tests/exrom): the MMC5",
                       "# two frames, past the PPU warm-up (the CPU waits for vblank)", "fs 2", "r pc = e020"]

    def step(self, instrs, *asserts):
        self.code += b"".join(instrs)
        if instrs:
            self.script.append("t %d" % len(instrs))
        self.script += ["!assert " + a for a in asserts]

    def reg(self, addr, value, *asserts):
        self.step([lda(value), sta(addr)], *asserts)

    def ppu_write(self, addr, value, *asserts):
        self.step([lda(addr >> 8), sta(0x2006), lda(addr & 0xFF), sta(0x2006), lda(value), sta(0x2007)], *asserts)

    def ppu_read(self, addr, ram, *asserts):  # buffered: one dummy read
        self.step([lda(addr >> 8), sta(0x2006), lda(addr & 0xFF), sta(0x2006), lda_abs(0x2007), lda_abs(0x2007),
                   sta(ram)], *asserts)

    def chr_is(self, addr, bank, ram):
        """The PPU reads 1KB bank BANK at ADDR (stored at RAM, asserted)."""
        self.ppu_read(addr, ram, "mem %04x %02x" % (ram, bank))


def rom(prog, chr_data=None):
    chr_banks = 8 if chr_data is None else len(chr_data) // 0x2000
    header = bytes([ord("N"), ord("E"), ord("S"), 0x1A, 8, chr_banks, 0x50, 0, 0, 0, 0, 0, 0, 0, 0, 0])
    banks = []
    for b in range(16):
        d = bytearray(0x2000)
        d[0x20:0x20 + len(prog.code)] = prog.code
        # reset: wait for two vblanks (the PPU warm-up), then on to the program (a script sets the PC itself)
        d[0x0D:0x1A] = (lda_abs(0x2002) + bytes([0x10, 0xFB]) + lda_abs(0x2002) + bytes([0x10, 0xFB]) +
                        bytes([0x4C, 0x20, 0xE0]))
        d[0x600:0x600 + 9] = inc_abs(0x0310) + lda_abs(0x5204) + bytes([0x40])  # INC $0310 / LDA $5204 / RTI
        d[0x1FFA:0x2000] = bytes([0, 0, 0x0D, 0xE0, 0x00, 0xE6])  # NMI, RESET = $E00D, IRQ = $E600
        d[0] = 0xB0 + b  # (the marker overlaps nothing: the program starts at $10)
        banks.append(bytes(d))
    if chr_data is None:
        chr_data = b"".join(bytes([n]) + bytes(0x3FF) for n in range(64))
    return header + b"".join(banks) + chr_data


def build():
    p = Prog()
    # --- power-on (Mesen's): mode 3, the last ROM bank at $E000, PRG-RAM page 0 (zeros) at $8000-$DFFF
    p.step([], "mem 8000 00", "mem a000 00", "mem c000 00", "mem e000 bf")
    # --- PRG mode 3: four 8KB banks (ROM when bit 7 is set)
    p.reg(0x5100, 3)
    p.reg(0x5114, 0x82, "mem 8000 b2")
    p.reg(0x5115, 0x85, "mem a000 b5")
    p.reg(0x5116, 0x87, "mem c000 b7", "mem e000 bf")
    # --- mode 2: 16KB at $8000 (bit 0 of the bank ignored), 8KB at $C000, 8KB fixed at $E000
    p.reg(0x5100, 2)
    p.reg(0x5115, 0x85, "mem 8000 b4", "mem a000 b5")
    p.reg(0x5116, 0x89, "mem c000 b9", "mem e000 bf")
    # --- mode 1: 16KB at $8000 and 16KB at $C000 (the second one changes the bank under the program)
    p.reg(0x5100, 1)
    p.reg(0x5115, 0x86, "mem 8000 b6", "mem a000 b7")
    p.reg(0x5117, 0x8B, "mem c000 ba", "mem e000 bb")
    # --- mode 0: 32KB from $5117 (bits 0-1 ignored)
    p.reg(0x5100, 0)
    p.reg(0x5117, 0x89, "mem 8000 b8", "mem a000 b9", "mem c000 ba", "mem e000 bb")
    p.reg(0x5100, 3)
    p.reg(0x5117, 0xFF, "mem e000 bf")
    # --- PRG-RAM: 64KB, protected until $5102 = 2 and $5103 = 1; 8KB banks at $6000 ($5113) and RAM at $8000 (bit 7 clear)
    p.reg(0x5113, 0)
    p.step([lda(0x5A), sta(0x6000)], "mem 6000 00")  # protected: the write is ignored
    p.reg(0x5102, 2)
    p.step([lda(0x5A), sta(0x6000)], "mem 6000 00")  # one key is not enough
    p.reg(0x5103, 1)
    p.step([lda(0x5A), sta(0x6000)], "mem 6000 5a")
    p.reg(0x5113, 5, "mem 6000 00")
    p.step([lda(0x77), sta(0x6001)], "mem 6001 77")
    p.reg(0x5113, 0, "mem 6000 5a", "mem 6001 00")
    p.reg(0x5113, 0x0D, "mem 6001 77")  # bank 13 of the 8 (wraps: 13 % 8 = 5)
    p.reg(0x5113, 0)
    p.reg(0x5114, 0x00, "mem 8000 5a")  # RAM page 0 at $8000
    p.step([lda(0x33), sta(0x8002)], "mem 8002 33", "mem 6002 33")
    p.reg(0x5102, 0)
    p.step([lda(0x44), sta(0x6002)], "mem 6002 33")  # protected again
    p.reg(0x5114, 0x82, "mem 8000 b2")
    # --- the debugger's memory edit goes to the RAM page mapped now ($5113 for $6000, the bank register of a RAM slot), not to page 0
    p.script += ["eb 6010 = 99", "!assert mem 6010 99"]
    p.reg(0x5113, 5, "mem 6010 00")
    p.script += ["eb 6010 = 77", "!assert mem 6010 77"]
    p.reg(0x5113, 0, "mem 6010 99")  # (page 0 kept its byte)
    p.reg(0x5114, 0x00)  # RAM page 0 at $8000
    p.script += ["eb 8011 = 66", "!assert mem 8011 66", "!assert mem 6011 66"]
    p.reg(0x5114, 0x82, "mem 8000 b2")
    # --- CHR mode 3: eight 1KB banks (set A, $5120-$5127)
    p.reg(0x5101, 3)
    p.reg(0x5120, 10)
    p.chr_is(0x0000, 10, 0x0300)
    p.reg(0x5121, 11)
    p.chr_is(0x0400, 11, 0x0301)
    p.reg(0x5127, 63)
    p.chr_is(0x1C00, 63, 0x0302)
    # mode 0: one 8KB bank from $5127
    p.reg(0x5101, 0)
    p.reg(0x5127, 2)
    p.chr_is(0x0000, 16, 0x0303)
    p.chr_is(0x1C00, 23, 0x0304)
    # mode 1: 4KB banks from $5123 and $5127
    p.reg(0x5101, 1)
    p.reg(0x5123, 3)
    p.reg(0x5127, 5)
    p.chr_is(0x0000, 12, 0x0305)
    p.chr_is(0x0C00, 15, 0x0306)
    p.chr_is(0x1000, 20, 0x0307)
    # mode 2: 2KB banks from $5121, $5123, $5125, $5127
    p.reg(0x5101, 2)
    p.reg(0x5121, 7)
    p.reg(0x5125, 9)
    p.chr_is(0x0000, 14, 0x0308)
    p.chr_is(0x0400, 15, 0x0309)
    p.chr_is(0x1000, 18, 0x030A)
    p.chr_is(0x1400, 19, 0x030B)
    # --- sets A and B: 8x8 sprites use A for everything; with 8x16 sprites the CPU's $2007 reads use the set written last
    p.reg(0x5101, 3)
    p.reg(0x5120, 20)
    p.reg(0x5128, 30)
    p.reg(0x5129, 31)
    p.reg(0x2000, 0x00)
    p.chr_is(0x0000, 20, 0x030C)  # 8x8: set A
    p.reg(0x2000, 0x20)
    p.chr_is(0x0000, 30, 0x030D)  # 8x16, set B written last
    p.chr_is(0x1400, 31, 0x030E)  # (B repeats in both halves: $5129 at $0400 and $1400)
    p.reg(0x5120, 21)
    p.chr_is(0x0000, 21, 0x030F)  # set A written last
    p.reg(0x2000, 0x00)
    # --- name tables: $5105 gives each of the four a source: 0 CIRAM page 0, 1 CIRAM page 1, 2 ExRAM, 3 fill mode
    p.reg(0x5105, 0x44)  # vertical
    p.ppu_write(0x2000, 0x31)
    p.ppu_read(0x2800, 0x0320, "mem 0320 31")
    p.ppu_read(0x2400, 0x0321, "mem 0321 00")
    p.reg(0x5105, 0x50)  # horizontal
    p.ppu_write(0x2000, 0x32)
    p.ppu_read(0x2400, 0x0322, "mem 0322 32")
    p.reg(0x5106, 0x66)
    p.reg(0x5107, 2)
    p.reg(0x5105, 0xFF)  # all fill mode: the tile, and the attribute bits in all four quadrants
    p.ppu_read(0x2000, 0x0323, "mem 0323 66")
    p.ppu_read(0x23C0, 0x0324, "mem 0324 aa")
    p.ppu_read(0x2FFF, 0x0325, "mem 0325 aa")
    p.reg(0x5105, 0xAA)  # all ExRAM
    p.ppu_write(0x2001, 0x44)
    p.ppu_read(0x2401, 0x0326, "mem 0326 44")  # the same 1KB
    p.reg(0x5104, 2)  # ExRAM as RAM: the CPU reads it, and as a name table it reads 0
    p.step([], "mem 5c01 44")
    p.ppu_read(0x2001, 0x0327, "mem 0327 00")
    p.step([lda(0x99), sta(0x5C05)], "mem 5c05 99")
    p.reg(0x5104, 3)
    p.step([lda(0x11), sta(0x5C05)], "mem 5c05 99")  # read only
    p.reg(0x5104, 0)
    p.step([], "mem 5c05 5c")  # (as a name table: not readable by the CPU)
    p.reg(0x5105, 0x44)
    # --- the multiplier
    p.reg(0x5205, 7)
    p.reg(0x5206, 9)
    p.step([lda_abs(0x5205), sta(0x0330), lda_abs(0x5206), sta(0x0331)], "mem 0330 3f", "mem 0331 00")  # (the CPU reads it: 63)
    p.reg(0x5205, 200)
    p.reg(0x5206, 100)
    p.step([lda_abs(0x5205), sta(0x0330), lda_abs(0x5206), sta(0x0331)], "mem 0330 20", "mem 0331 4e")  # 20000
    # --- the scanline IRQ: BG on, compare 10, enabled; the routine counts and acknowledges. One IRQ a frame, in line 10
    p.reg(0x4017, 0x40)  # (no APU frame IRQ: the routine would run for it too)
    p.step([lda_abs(0x4015)])
    p.step([lda(0), sta(0x0310)])
    p.reg(0x5203, 10)
    p.reg(0x2001, 0x08)
    p.reg(0x5204, 0x80)
    p.step([CLI])
    here = BASE + 0x20 + len(p.code)
    p.code += bytes([0x4C, here & 0xFF, here >> 8])  # JMP * at the end of the program
    assert len(p.code) < 0x5E0
    p.script += ["bpx e600", "g", "!assert reg pc e600", "!assert scanline 10", "bc *",
                 "fs 1", "fs 4", "!assert mem 0310 05"]
    return p


# --- pictures: extended attributes (ExRAM mode 1) and the vertical split. CHR bank k of 4KB is solid colour k & 3, so a tile's pixels
# say which bank (colour index) and which palette it was drawn with. The script runs the program, takes a screenshot, and
# pic_check.py compares pixels (relations only: ONE and the NES palette colours are not repeated here). The split test has no
# Mesen reference yet: it checks what the MMC5 documentation says (columns left of the boundary, the ExRAM name table's own bank
# and palette, the main picture right of it)
def ldx(n):
    return bytes([0xA2, n])


def sta_x(addr):
    return bytes([0x9D, addr & 0xFF, addr >> 8])


INX = bytes([0xE8])


def bne_back(n):
    return bytes([0xD0, (256 - n) & 0xFF])


def fill_page_loop(value_code, addrs):
    """X from 0 to 255: A = value_code (an instruction sequence), stored at each address + X"""
    body = value_code + b"".join(sta_x(a) for a in addrs) + INX
    return ldx(0) + body + bne_back(len(body) + 2)


def pic_chr():
    data = bytearray()
    for bank in range(16):
        tile = bytes([0xFF if bank & 1 else 0] * 8 + [0xFF if bank & 2 else 0] * 8)
        data += tile * 256
    return bytes(data)


def pic_program(kind):
    # palettes: backdrop, then four palettes of three colours (index 0 of each is the backdrop)
    pal = [0x0F, 0x16, 0x2A, 0x12, 0x0F, 0x26, 0x3A, 0x22, 0x0F, 0x06, 0x1A, 0x02, 0x0F, 0x36, 0x2C, 0x32]
    code = lda(0x3F) + sta(0x2006) + lda(0x00) + sta(0x2006)
    for c in pal:
        code += lda(c) + sta(0x2007)
    code += lda(0x20) + sta(0x2006) + lda(0x00) + sta(0x2006)  # (v and t back to the top left of name table 0)
    code += lda(0x00) + sta(0x2000)  # BG pattern table $0000, 8x8 sprites (the name tables are zero: tile 0)
    code += lda(2) + sta(0x5104)     # ExRAM as RAM: fill it
    code += lda(1) + sta(0x5101)     # CHR mode 1: 4KB banks, $5123 for the background
    if kind == "exattr":
        # ExRAM byte of tile (c, r): palette r & 3 (bits 6-7), bank c & 3 (bits 0-5). One loop over the 32 columns per row:
        # TXA / AND #3 / ORA #palette / STA $5C00+32r,X / INX / CPX #32 / BNE
        for r in range(30):
            loop = bytes([0x8A, 0x29, 0x03, 0x09, (r & 3) << 6]) + sta_x(0x5C00 + 32 * r) + INX + bytes([0xE0, 32])
            code += ldx(0) + loop + bne_back(len(loop) + 2)
        code += lda(1) + sta(0x5104)  # extended attributes
        code += lda(0) + sta(0x5200)
    else:
        code += fill_page_loop(lda(0), [0x5C00, 0x5D00, 0x5E00, 0x5F00])  # tiles 0, attributes 0
        code += lda(0x55) + ldx_attr_loop()                               # attributes: palette 1 everywhere
        code += lda(0) + sta(0x5104)
        code += lda(0x80 | (0x40 if kind == "split_right" else 0) | 16) + sta(0x5200)  # boundary: tile 16
        code += lda(0) + sta(0x5201)
        code += lda(2) + sta(0x5202)  # the split area uses bank 2: colour index 2
    code += lda(3) + sta(0x5123)      # main picture: bank 3, colour index 3
    code += lda(0x0A) + sta(0x2001)   # background on
    here = BASE + 0x20 + len(code)
    code += bytes([0x4C, here & 0xFF, here >> 8])
    return code


def ldx_attr_loop():
    """STA $5FC0..$5FFF (the split's attribute bytes, A = value)"""
    body = sta_x(0x5FC0) + INX + bytes([0xE0, 0x40])
    return ldx(0) + body + bne_back(len(body) + 2)


def pic_roms():
    for kind in ("exattr", "split_left", "split_right"):
        class P:
            pass
        p = P()
        p.code = pic_program(kind)
        assert len(p.code) < 0x5E0, len(p.code)
        with open(os.path.join(HERE, "pic_%s.nes" % kind), "wb") as f:
            f.write(rom(p, pic_chr()))
        with open(os.path.join(HERE, "pic_%s.txt" % kind), "w") as f:
            f.write("# generated by gen.py: the picture of pic_%s.nes\nfs 2\nr pc = e020\nfs 8\nscreenshot pic_%s.png\n" % (kind, kind))


# --- the corners of the split and of the CHR banks: Mesen's pictures of these ROMs are the reference (tests/exrom/*_mesen.png)
# split_scroll_a / _b: the split with $5201 (its vertical scroll) 13 and 235 (a wrap at 240 is near) and $5202 (its bank) 5 and 9, on the
#     left of tile 16 and on the right of tile 8. Every tile of the split's name table (in ExRAM) and of the main one has its own number
#     and CHR tiles are striped (the colour of a row of a tile is (row + tile + bank) & 3): the picture shows the tile, the fine
#     scroll and the bank. The split's attribute bytes $E4 give each quadrant of a 32x32 pixel area its own palette.
# exattr_scroll: extended attributes with the PPU scrolled by (11, 21): the tiles of the first line fetched before the frame starts
# chr1m: a 1 MB CHR-ROM and the upper CHR bits ($5130): four stripes of the picture show 1 KB banks 1, 262, 523 and 1022 (CHR mode 3)
#     as three bands of a tile: the colour of bits 8-9 of the bank number, of bits 2-3, and of bits 0-1
# chr1m_exattr: the same 1 MB with extended attributes: $5130 = 2 gives the 4 KB banks of the tiles bits 6-7: 2
# split_8x16: the split with 8x16 sprites (the background reads CHR set B, the sprites set A, eight sprites cross the boundary);
#     split_mode1: the split with ExRAM mode 1 (the same ExRAM is the split's name table and the other tiles' extended attributes);
#     split_wrap: $5201 = 238, so the split's rows wrap at 240 in the first lines
# chr1m_mode0/1/2: the upper CHR bits with 8 KB, 4 KB and 2 KB banks (a 1 MB CHR makes the numbers wrap)
def chr_rot():
    data = bytearray()
    for bank in range(16):
        for tile in range(256):
            lo, hi = bytearray(), bytearray()
            for row in range(8):
                color = (row + tile + bank) & 3
                lo.append(0xFF if color & 1 else 0)
                hi.append(0xFF if color & 2 else 0)
            data += lo + hi
    return bytes(data)


def chr_hash():
    """1 MB: 1 KB bank n is 64 tiles of three bands: rows 0-2 the colour (n >> 8) & 3, rows 3-5 (n >> 2) & 3, rows 6-7 n & 3"""
    data = bytearray()
    for n in range(1024):
        lo, hi = bytearray(), bytearray()
        for row in range(8):
            color = ((n >> 8) & 3) if row < 3 else (((n >> 2) & 3) if row < 6 else (n & 3))
            lo.append(0xFF if color & 1 else 0)
            hi.append(0xFF if color & 2 else 0)
        data += (lo + hi) * 64
    return bytes(data)


def palettes():
    pal = [0x0F, 0x16, 0x2A, 0x12, 0x0F, 0x26, 0x3A, 0x22, 0x0F, 0x06, 0x1A, 0x02, 0x0F, 0x36, 0x2C, 0x32]
    code = lda(0x3F) + sta(0x2006) + lda(0x00) + sta(0x2006)
    for c in pal:
        code += lda(c) + sta(0x2007)
    return code


def pic2_program(kind):
    code = palettes()
    if kind == "split_8x16":  # the sprite palettes too ($3F10-$3F1F: the same colours)
        code += palettes().replace(lda(0x00) + sta(0x2006), lda(0x10) + sta(0x2006), 1)
    code += lda(0x20) + sta(0x2006) + lda(0x00) + sta(0x2006)  # v: the top left of name table 0
    if kind.startswith("chr1m"):
        # name table 0: 8 columns of tiles 0, 64, 128, 192 (the first tile of each of the four 1 KB banks of the pattern table)
        for _ in range(30):
            loop = bytes([0x8A, 0x29, 0x18, 0x0A, 0x0A, 0x0A]) + sta(0x2007) + INX + bytes([0xE0, 32])
            code += ldx(0) + loop + bne_back(len(loop) + 2)
        code += lda(0) + sta(0x2005) + sta(0x2005)
    else:
        for _ in range(4):  # name table 0: every tile its own number (the position modulo 256), the attribute bytes too
            loop = bytes([0x8E, 0x07, 0x20]) + INX
            code += ldx(0) + loop + bne_back(len(loop) + 2)
        if kind == "exattr_scroll":
            code += lda(11) + sta(0x2005) + lda(21) + sta(0x2005)
        else:
            code += lda(0) + sta(0x2005) + sta(0x2005)
    code += lda(0x20 if kind == "split_8x16" else 0x00) + sta(0x2000)  # BG pattern table $0000, 8x8 (8x16: split_8x16) sprites
    if kind.startswith("split"):
        code += lda(2) + sta(0x5104) + lda(1) + sta(0x5101)
        for r in range(30):  # the split's tiles: (7 * row + column) & 255
            loop = bytes([0x8A, 0x18, 0x69, (7 * r) & 0xFF]) + sta_x(0x5C00 + 32 * r) + INX + bytes([0xE0, 32])
            code += ldx(0) + loop + bne_back(len(loop) + 2)
        code += lda(0xE4) + ldx_attr_loop()  # the attributes: a palette for each quadrant
        code += lda(1 if kind == "split_mode1" else 0) + sta(0x5104)
        scroll, bank, control = {"split_scroll_a": (13, 5, 0x80 | 16), "split_scroll_b": (235, 9, 0x80 | 0x40 | 8),
                                 "split_8x16": (13, 5, 0x80 | 16), "split_mode1": (13, 5, 0x80 | 16),
                                 "split_wrap": (238, 6, 0x80 | 16)}[kind]
        code += lda(control) + sta(0x5200) + lda(scroll) + sta(0x5201) + lda(bank) + sta(0x5202)
        if kind == "split_8x16":
            # 8x16 sprites: the background reads set B ($512B in mode 1: 4 KB at both $0000 and $1000), the sprites set A
            code += lda(3) + sta(0x512B) + lda(7) + sta(0x5123) + lda(9) + sta(0x5127)
            code += lda(0) + sta(0x2003)
            for y, tile, attr, x in ((20, 0x02, 0x00, 24), (20, 0x03, 0x01, 112), (60, 0x04, 0x02, 120), (100, 0x05, 0x03, 130),
                                     (140, 0x06, 0x00, 60), (140, 0x07, 0x01, 200), (180, 0x08, 0x02, 124), (200, 0x09, 0x03, 8)):
                for v in (y, tile, attr, x):
                    code += lda(v) + sta(0x2004)
        else:
            code += lda(3) + sta(0x5123)
    elif kind == "exattr_scroll":
        code += lda(2) + sta(0x5104) + lda(1) + sta(0x5101)
        for r in range(30):  # palette row & 3, bank (column + 3 * row) & 63
            loop = (bytes([0x8A, 0x18, 0x69, (3 * r) & 0xFF, 0x29, 0x3F, 0x09, (r & 3) << 6]) + sta_x(0x5C00 + 32 * r) + INX +
                    bytes([0xE0, 32]))
            code += ldx(0) + loop + bne_back(len(loop) + 2)
        code += lda(1) + sta(0x5104)
    elif kind == "chr1m":
        code += lda(3) + sta(0x5101)  # 1 KB banks: $5120-$5123 are the pattern table at $0000
        for slot, (upper, low) in enumerate(((0, 1), (1, 6), (2, 11), (3, 254))):
            code += lda(upper) + sta(0x5130) + lda(low) + sta(0x5120 + slot)
    elif kind in ("chr1m_mode0", "chr1m_mode1", "chr1m_mode2"):
        # the upper bits with bigger banks: 8 KB ($5127), 4 KB ($5123), 2 KB ($5121, $5123). With 1 MB of CHR the bank numbers wrap:
        # 8 KB banks to 7 bits, 4 KB to 8 bits, 2 KB to 9 bits: only 2 KB banks keep $5130 bit 0 (bit 1 wraps)
        if kind == "chr1m_mode0":
            code += lda(0) + sta(0x5101) + lda(2) + sta(0x5130) + lda(0x15) + sta(0x5127)
        elif kind == "chr1m_mode1":
            code += lda(1) + sta(0x5101) + lda(3) + sta(0x5130) + lda(0xA5) + sta(0x5123)
        else:
            code += lda(2) + sta(0x5101) + lda(1) + sta(0x5130) + lda(0x35) + sta(0x5121)
            code += lda(2) + sta(0x5130) + lda(0x07) + sta(0x5123)
    elif kind == "chr1m_exattr":
        code += lda(2) + sta(0x5104) + lda(1) + sta(0x5101)
        for r in range(30):  # the tiles' 4 KB banks: (column + 3 * row) & 63, palette row & 3
            loop = (bytes([0x8A, 0x18, 0x69, (3 * r) & 0xFF, 0x29, 0x3F, 0x09, (r & 3) << 6]) + sta_x(0x5C00 + 32 * r) + INX +
                    bytes([0xE0, 32]))
            code += ldx(0) + loop + bne_back(len(loop) + 2)
        code += lda(2) + sta(0x5130)      # the upper bits: bits 6-7 of the 4 KB bank number
        code += lda(1) + sta(0x5104)
    code += lda(0x1E if kind == "split_8x16" else 0x0A) + sta(0x2001)   # background on (and the sprites for split_8x16)
    here = BASE + 0x20 + len(code)
    code += bytes([0x4C, here & 0xFF, here >> 8])
    return code


PIC2_KINDS = ("split_scroll_a", "split_scroll_b", "exattr_scroll", "chr1m", "chr1m_exattr", "split_8x16", "split_mode1", "split_wrap",
              "chr1m_mode0", "chr1m_mode1", "chr1m_mode2")


def view_scripts():
    """The debugger's own views of two of the pictures: the background window (wbg) of pic_chr1m_exattr (the tiles' own banks and palettes,
    with $5130, must show, as the picture does) and the pattern window (wpat) of pic_split_8x16 (its two tables are different CHR sets)"""
    with open(os.path.join(HERE, "pic_exattr_view.txt"), "w") as f:  # (chr1m_exattr: the scroll is 0, so that the picture is at the top left of the map)
        f.write("# generated by gen.py: the picture, and the background window, of pic_chr1m_exattr.nes\nfs 2\nr pc = e020\nfs 8\n"
                "screenshot pic_exattr_view.png\nwbg save pic_exattr_wbg.png\n")
    with open(os.path.join(HERE, "pic_split_8x16_wpat.txt"), "w") as f:
        f.write("# generated by gen.py: the pattern window of pic_split_8x16.nes\nfs 2\nr pc = e020\nfs 8\nwpat save pic_split_8x16_wpat.png\n")


def pic2_roms():
    view_scripts()
    for kind in PIC2_KINDS:
        class P:
            pass
        p = P()
        p.code = pic2_program(kind)
        assert len(p.code) < 0x5E0, (kind, len(p.code))
        with open(os.path.join(HERE, "pic_%s.nes" % kind), "wb") as f:
            f.write(rom(p, chr_hash() if kind.startswith("chr1m") else chr_rot()))
        with open(os.path.join(HERE, "pic_%s.txt" % kind), "w") as f:
            f.write("# generated by gen.py: the picture of pic_%s.nes\nfs 2\nr pc = e020\nfs 8\nscreenshot pic_%s.png\n" % (kind, kind))


