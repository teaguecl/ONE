def camerica():
    p = Prog("camerica")
    p.step([], "mem 8000 b0", "mem c000 b3")  # the last bank is fixed at $C000
    p.reg(2, 0xC100, "mem 8000 b2", "mem c000 b3")  # a write to $C000-$FFFF picks the bank at $8000
    p.reg(6, 0xC123, "mem 8000 b2")  # 6 wraps around the 4 banks; and no bus conflict (the ROM byte is $23)
    p.reg(1, 0xA000, "mem 8000 b2")  # $8000-$BFFF does not
    p.ppu_write(0x0123, 0x5A)
    p.ppu_read(0x0123, 0x0300, "mem 0300 5a")  # CHR-RAM
    # Fire Hawk's mirroring: header (vertical) until $9000-$9FFF bit 4 picks a one-screen page
    p.ppu_write(0x2000, 0x11)
    p.ppu_read(0x2800, 0x0301, "mem 0301 11")  # vertical: $2000 = $2800
    p.ppu_read(0x2400, 0x0302, "mem 0302 00")
    p.reg(0x10, 0x9000)  # one-screen, page 1
    p.ppu_write(0x2000, 0x22)
    p.ppu_read(0x2C00, 0x0303, "mem 0303 22")
    p.reg(0x00, 0x9FFF)  # page 0 again: the $11 written first
    p.ppu_read(0x2400, 0x0304, "mem 0304 11")
    write(p, rom(p, 71, 4, 0x4000, 0, 1, fixed_last=True))


