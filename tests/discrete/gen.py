def rom8(prog, mapper, prg8, chr1k, mirroring, sub=0):
    """prg8 8KB PRG banks (marker $B0+bank at the bank's first byte; the program is in the last, fixed at $E000: JMP * at
    $E00D = RESET, program at $E010); chr1k 1KB CHR banks (marker $40+bank at each 1KB)."""
    header = bytes([ord("N"), ord("E"), ord("S"), 0x1A, prg8 // 2, chr1k // 8,
                    ((mapper & 0x0F) << 4) | mirroring, 0x08 | (mapper & 0xF0), sub << 4, 0, 0, 0, 0, 0, 0, 0])
    banks = []
    for b in range(prg8):
        d = bytearray(0x2000)
        d[0] = 0xB0 + b
        if b == prg8 - 1:
            d[0x0D:0x10] = bytes([0x4C, 0x0D, 0xE0])
            d[0x10:0x10 + len(prog.code)] = prog.code
            d[0x2000 - 6:] = bytes([0, 0, 0x0D, 0xE0, 0, 0])
        banks.append(bytes(d))
    chr_data = b"".join(bytes([0x40 + k]) + bytes(0x3FF) for k in range(chr1k))
    return header + b"".join(banks) + chr_data


