"""Makes the test ROMs and --batch scripts of the one-latch mappers (tests/CMakeLists.txt, debugger_mapper_*):
UxROM (2), AxROM (7), Color Dreams (11), BNROM (34), GxROM (66), Camerica (71), Irem 74161 (78), NINA-003 (79).  Run: python3 gen.py  (writes next to this file).

Every ROM is NES 2.0 with submapper 2 (bus conflicts on, in the Mesen-compatible build too).  Each PRG bank starts
with a marker byte ($B0+bank at $8000; the 32KB boards also $C0+bank at $C000).  The reset vector points to a JMP * at $C00D (the script runs two frames, for the PPU warm-up, then sets the PC);
the program sits at $C010 (in the
fixed bank, or copied into every bank) and the table TAB at $C100 holds TAB[i] = i, so that "LDA #v / STA TAB+v" writes
v to the register without a conflict and "LDA #v / STA TAB+m" writes v & m.  The script steps through the program
with `t` and asserts what the CPU sees."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TAB = 0xC100


def lda(v):
    return bytes([0xA9, v])


def sta(a):
    return bytes([0x8D, a & 0xFF, a >> 8])


def lda_abs(a):
    return bytes([0xAD, a & 0xFF, a >> 8])


class Prog:
    def __init__(self, name, pc=0xC010):
        self.name = name
        self.code = b""
        self.script = ["# generated by gen.py: %s" % name, "# two frames, past the PPU warm-up (the CPU idles in a JMP *)", "fs 2", "r pc = %04x" % pc]

    def step(self, instrs, *asserts):
        """INSTRS: list of byte strings, one instruction each."""
        self.code += b"".join(instrs)
        if instrs:
            self.script.append("t %d" % len(instrs))
        self.script += ["!assert " + a for a in asserts]

    def select(self, value, at, *asserts):
        """Write VALUE to the latch through TAB+AT (the ROM byte there is AT: the latch gets VALUE & AT)."""
        self.step([lda(value), sta(TAB + at)], *asserts)

    def reg(self, value, addr, *asserts):
        """Write VALUE to ADDR (a board without bus conflicts, or a register outside the ROM)."""
        self.step([lda(value), sta(addr)], *asserts)

    def ppu_write(self, addr, value, *asserts):
        self.step([lda(addr >> 8), sta(0x2006), lda(addr & 0xFF), sta(0x2006), lda(value), sta(0x2007)], *asserts)

    def ppu_read(self, addr, ram, *asserts):  # buffered: one dummy read
        self.step([lda(addr >> 8), sta(0x2006), lda(addr & 0xFF), sta(0x2006), lda_abs(0x2007), lda_abs(0x2007),
                   sta(ram)], *asserts)


def rom(prog, mapper, prg_banks, prg_size, chr_banks, mirroring, fixed_last=False, sub=2, chr4=False):
    """prg_banks banks of prg_size bytes; chr_banks 8KB CHR-ROM banks (0: CHR-RAM); chr4: a marker $D0+k at each 4KB k."""
    header = bytes([ord("N"), ord("E"), ord("S"), 0x1A, (prg_banks * prg_size) // 0x4000, chr_banks,
                    ((mapper & 0x0F) << 4) | mirroring, 0x08 | (mapper & 0xF0), sub << 4, 0, 0, 0, 0, 0, 0, 0])
    banks = []
    for b in range(prg_banks):
        d = bytearray(prg_size)
        if prg_size == 0x4000:
            code_base = 0
            d[0] = 0xB0 + b
        else:
            code_base = 0x4000
            d[0] = 0xB0 + b
            d[0x4000] = 0xC0 + b
        if not fixed_last or b == prg_banks - 1:
            d[code_base + 0x0D:code_base + 0x10] = bytes([0x4C, 0x0D, 0xC0])  # JMP *
            d[code_base + 0x10:code_base + 0x10 + len(prog.code)] = prog.code
            d[code_base + 0x100:code_base + 0x200] = bytes(range(256))
            end = code_base + 0x4000
            d[end - 6:end] = bytes([0, 0, 0x0D, 0xC0, 0, 0])  # NMI, RESET = $C00D, IRQ
        banks.append(bytes(d))
    if chr4:
        chr_data = b"".join(bytes([0xD0 + k]) + bytes(0xFFF) for k in range(chr_banks * 2))
    else:
        chr_data = b"".join(bytes([0xD0 + c]) + bytes(0x1FFF) for c in range(chr_banks))
    return header + b"".join(banks) + chr_data


def write(prog, data):
    with open(os.path.join(HERE, prog.name + ".nes"), "wb") as f:
        f.write(data)
    with open(os.path.join(HERE, prog.name + ".txt"), "w") as f:
        f.write("\n".join(prog.script) + "\n")


def uxrom():
    p = Prog("uxrom")
    p.step([], "mem 8000 b0", "mem c000 b3")  # power-on: bank 0 at $8000, the last one fixed
    p.select(2, 2, "mem 8000 b2", "mem c000 b3")
    p.select(3, 1, "mem 8000 b1")  # bus conflict: 3 & 1
    p.select(6, 6, "mem 8000 b2", "mem c000 b3")  # 6 wraps around the 4 banks
    p.ppu_write(0x0123, 0x5A)
    p.ppu_read(0x0123, 0x0300, "mem 0300 5a")  # CHR-RAM
    p.ppu_write(0x1FFF, 0xA5)
    p.ppu_read(0x1FFF, 0x0301, "mem 0301 a5")
    write(p, rom(p, 2, 4, 0x4000, 0, 1, fixed_last=True))


