def tile(ch):
    rows = G.get(ch)
    if rows is None:
        return bytes(16)
    p0 = bytes(sum(1 << (6 - i) for i, c in enumerate(r) if c == '#') for r in rows) + b"\0"
    return p0 + bytes(8)

def ident(n, tag):
    return bytes([n, n ^ 0xFF]) + tag.ljust(14).encode()[:14]

out = sys.argv[1]
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "banks.bin"), "wb") as f:
    for n in range(31):
        f.write(ident(n, "RAMBO-1 PRG ID") + bytes([n]) * (0x2000 - 16))
font = b"".join(tile(chr(32 + i)) for i in range(63))        # tile = ASCII - 32, ASCII 32..94
with open(os.path.join(out, "chr.bin"), "wb") as f:
    for n in range(256):
        f.write(font + ident(n, "RAMBO-1 CHR ID"))
