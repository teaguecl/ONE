"""Writes sweep_data.inc for sweep.s (the Zapper palette sweep ROM) and describes its layout for sweep_analyze.py.

  make_sweep.py            write sweep_data.inc next to this file

Layout: 4 rows x 3 columns of 32x32 pixel squares, one background palette per row and its colors 1-3 in the columns.
A "page" is 12 NES colors, in order $00-$3F (the last page is padded with $0F), 6 pages. The squares' positions:
X = 48, 112, 176 and Y = 16, 64, 112, 160."""
import os

COLS_X = (48, 112, 176)
ROWS_Y = (16, 64, 112, 160)
SIZE = 32
PAGES = 6


def page_colors(page):
    """The 12 colors of a page, row by row (palette 0 entries 1-3, palette 1 entries 1-3 ...)"""
    colors = list(range(page * 12, min(64, page * 12 + 12)))
    return colors + [0x0F] * (12 - len(colors))


def square_at(x, y):
    """(row, column 0-2) of the square holding the pixel, or None"""
    for r, sy in enumerate(ROWS_Y):
        for c, sx in enumerate(COLS_X):
            if sx <= x < sx + SIZE and sy <= y < sy + SIZE:
                return r, c
    return None


def main():
    nametable = bytearray(960)
    attributes = bytearray(64)
    for r, sy in enumerate(ROWS_Y):
        for c, sx in enumerate(COLS_X):
            for ty in range(sy // 8, (sy + SIZE) // 8):
                for tx in range(sx // 8, (sx + SIZE) // 8):
                    nametable[ty * 32 + tx] = c + 1  # tile 1-3: color 1-3 of the row's palette
            for cy in range(sy // 16, (sy + SIZE) // 16):  # attribute quadrants of 16x16 pixels
                for cx in range(sx // 16, (sx + SIZE) // 16):
                    index = (cy // 2) * 8 + cx // 2
                    shift = ((cy % 2) * 2 + (cx % 2)) * 2
                    attributes[index] = (attributes[index] & ~(3 << shift)) | (r << shift)
    lines = ["; generated by make_sweep.py: do not edit", ""]

    def table(label, data):
        lines.append(label + ":")
        for i in range(0, len(data), 16):
            lines.append("    .byte " + ", ".join("$%02X" % b for b in data[i:i + 16]))

    table("nametable_data", nametable + attributes)
    table("page_palettes", bytes(0x0F if i % 4 == 0 else page_colors(p)[i // 4 * 3 + i % 4 - 1] for p in range(PAGES) for i in range(16)))
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "sweep_data.inc"), "w") as out:
        out.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
